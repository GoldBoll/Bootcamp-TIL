// 백준 2852 - NBA 농구
// https://www.acmicpc.net/problem/2852

// 문제 설명
// 농구 경기는 정확히 48분(=2880초) 동안 진행된다.
// 골이 들어간 시각(MM:SS)과 팀(1 또는 2)이 시간순으로 주어진다.
// 각 팀이 몇 분 동안 "이기고 있었는지"를 MM:SS 형식으로 출력하라.

// 제약 조건
// 1 <= N <= 100
// 팀 번호 = 1 또는 2
// 시간 = MM:SS, 0 <= MM <= 47, 0 <= SS <= 59 (득점 시간 중복 없음)

// 예제
// 입력            출력
// 3              20:00
// 1 01:10        16:30
// 2 21:10
// 2 31:30

// 접근 (직접 채울 부분)
// - 득점과 득점 사이 구간마다 그 구간 동안 누가 앞서 있었는지 판정
// - 1번/2번 팀이 이긴 시간을 각각 누적, 마지막 득점 ~ 2880초 구간도 처리
// - 시간 복잡도 O(N)

#include <iostream>
#include <string>
using namespace std;
#define endl '\n'

int n;
int team[100];   // 각 득점의 팀 번호 (1 또는 2)
int sec[100];    // 각 득점 시각을 초로 환산 (MM:SS -> MM*60 + SS)

int main()
{
    cin >> n;
    for (int i = 0; i < n; i++)
    {
        string t;                 // "MM:SS" 형식
        cin >> team[i] >> t;

        // MM:SS -> 총 초로 변환
        int mm = (t[0] - '0') * 10 + (t[1] - '0');
        int ss = (t[3] - '0') * 10 + (t[4] - '0');
        sec[i] = mm * 60 + ss;
    }

    // ===== 여기부터 직접 풀기 =====
    // - 경기 종료는 48:00 = 2880초
    // - 득점과 득점 사이 구간마다 누가 이기고 있었는지 판정해 시간 누적
    // - 1번 팀이 이긴 시간, 2번 팀이 이긴 시간을 MM:SS 형식으로 출력
    //   (분 = w / 60, 초 = w % 60, 두 자리 0 패딩 — printf("%02d:%02d\n", ...) 등)

    return 0;
}
