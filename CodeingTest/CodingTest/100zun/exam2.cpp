// [알고리즘 시험 2] 계단 오르기 — 점화식을 직접 세운다  (33점)
//
// 문제 설명
// n개의 계단이 있고 한 번에 1칸 또는 2칸(Part B는 1·2·3칸)을 오를 수 있다.
// n번째 계단에 도달하는 서로 다른 방법의 수를 구하라.
//
// 접근 — DP 4단계 프레임
// ① 상태 정의: dp[i] = i번째 계단에 도달하는 방법의 수
// ② 점화식:
//    Part A (1·2칸)   : dp[i] = dp[i-1] + dp[i-2]            (피보나치)
//    Part B (1·2·3칸) : dp[i] = dp[i-1] + dp[i-2] + dp[i-3]  (트리보나치)
//    → i번째 직전에 있던 위치(1·2·(3)칸 전)의 방법 수를 모두 더한다.
// ③ 초기값: dp[0]=1(바닥 1가지), dp[1]=1, (Part B) dp[2]=2
// ④ 시간 복잡도 O(n)
//
// ── 소문항 답안 ─────────────────────────────────────────
// 1) dp[0] dp[1] → "1 1"
// 2) [TODO 2] Part A 점화식 → ① dp[i] = dp[i-1] + dp[i-2];
// 3) climbStairs3(12) → 927
//    트리보나치: 1,1,2,4,7,13,24,44,81,149,274,504,927
// 4) (서술) DP 없이 순수 재귀면 같은 계단의 방법 수를 중복 계산해,
//    호출 수가 O(2^n)으로 늘어나 n이 커지면 매우 느려진다.
// ────────────────────────────────────────────────────────

#include <iostream>
#include <vector>
#include <string>
using namespace std;

// ── Part A. 한 번에 1칸 또는 2칸 ──────────────────────────
long long climbStairs2(int n) {
    vector<long long> dp(n + 1, 0);

    dp[0] = 1;               // [TODO 1] 바닥에 그대로 있는 것도 1가지
    if (n >= 1) dp[1] = 1;   //          1번 계단: (1) 한 가지

    for (int i = 2; i <= n; i++) {
        // [TODO 2] 직전엔 i-1(1칸 전) 또는 i-2(2칸 전)
        dp[i] = dp[i - 1] + dp[i - 2];
    }
    return dp[n];
}

// ── Part B. 한 번에 1칸, 2칸, 또는 3칸 ────────────────────
long long climbStairs3(int n) {
    vector<long long> dp(n + 1, 0);

    dp[0] = 1;               // [TODO 3] 바닥 1가지
    if (n >= 1) dp[1] = 1;   //          (1)
    if (n >= 2) dp[2] = 2;   //          (1+1), (2) → 2가지

    for (int i = 3; i <= n; i++) {
        // [TODO 4] 직전엔 i-1·i-2·i-3 중 하나 (세 경우 합)
        dp[i] = dp[i - 1] + dp[i - 2] + dp[i - 3];
    }
    return dp[n];
}

// ───────────── 채점용 main (수정 금지) ─────────────
int main() {
    int pass = 0, total = 0;

    auto check = [&](long long got, long long expected, string name) {
        total++;
        bool ok = (got == expected);
        if (ok) pass++;
        cout << (ok ? "[PASS] " : "[FAIL] ") << name
             << " — 기대값 " << expected << ", 내 답 " << got << endl;
    };

    check(climbStairs2(1),  1,   "A-1: 계단 1개 (1·2칸)");
    check(climbStairs2(4),  5,   "A-2: 계단 4개 (1·2칸)");
    check(climbStairs2(10), 89,  "A-3: 계단 10개 (1·2칸)");
    check(climbStairs3(3),  4,   "B-1: 계단 3개 (1·2·3칸)");
    check(climbStairs3(10), 274, "B-2: 계단 10개 (1·2·3칸)");

    cout << endl << pass << " / " << total << " 통과"
         << (pass == total ? " — 완료! 다음 문제로 가세요." : " — TODO를 다시 살펴보세요.") << endl;
    return 0;
}

