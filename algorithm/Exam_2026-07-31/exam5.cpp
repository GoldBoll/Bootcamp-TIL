// [모의 코딩테스트 5] 꽃길 — 십자 꽃 세 개를 겹치지 않게 놓는 최소 비용
// 같은 문제: 백준 14620 꽃길  https://www.acmicpc.net/problem/14620
// 난이도: solved.ac 기준 Silver II (level 9) — 2026-07-31 조회

// 문제 설명
// N x N 격자에 씨앗 세 개를 심는다. 씨앗 하나는 심은 칸과 상하좌우 4칸, 총 5칸을 차지하는
// 십자 모양 꽃이 된다. 꽃끼리 한 칸이라도 겹치거나 꽃잎이 격자 밖으로 나가면 죽는다.
// 세 꽃이 모두 살아 있게 심을 때, 차지한 15칸의 대여 가격 합의 최솟값을 구한다.

// 제약 조건
// 6 <= N <= 10
// 0 <= 칸당 가격 <= 200
// 꽃잎이 밖으로 나가면 안 되므로 중심이 될 수 있는 칸은 테두리를 뺀 안쪽뿐 -> (N-2)^2 <= 64개
// 답의 상한 = 3송이 x 5칸 x 200 = 3,000

// 예제
// prices                                result
// [[1,0,2,3,3,4],
//  [1,1,1,1,1,1],
//  [0,0,1,1,1,1],
//  [3,9,9,0,1,99],
//  [9,11,3,1,0,3],
//  [12,3,0,0,0,1]]                      12
//   중심 (1,1) + (2,3) + (4,4) 로 3 + 4 + 5 = 12 (실측으로 확인한 최적 배치)
//   문제 설명에 적힌 (2,1)/(3,4)/(4,4) 는 (3,4)와 (4,4)가 서로 겹쳐 셋 다 죽는 배치다.
//   답 12 자체는 맞으므로 설명의 좌표만 잘못된 것으로 보고 진행했다.

// 자체 검증 케이스 (전부 실측 통과)
// N=6 전부 0                     0       최소 경계 — 어디에 놓아도 0
// N=6 전부 200                   3000    답의 상한 (3 x 5 x 200). int 범위 확인
// N=10 전부 1                    15      최대 격자 — 15칸이면 무조건 15
// N=6 가운데 2x2만 200, 나머지 0  0      비싼 칸을 통째로 피할 수 있는지 —
//                                        세 꽃이 가운데 네 칸을 전혀 안 밟고 배치된다
// 아래 그리디 반례 격자          21      "제일 싼 꽃부터" 그리디는 23을 내놓는다
// 무작위 격자 x 스트레스         (아래)
//
// [그리디 반례 격자 — 랜덤 탐색으로 직접 찾은 것]
//   {1,0,3,1,3,0}
//   {2,2,3,3,3,1}
//   {1,1,2,3,0,3}
//   {2,1,3,1,2,1}
//   {1,1,3,2,1,0}
//   {2,2,2,2,3,2}
//   5칸 합이 가장 싼 꽃부터 집는 그리디 -> 23 / 최적 -> 21.
//   첫 번째로 집은 싼 꽃이 그 뒤에 놓을 수 있었던 더 싼 조합 두 개를 동시에 막는다.

// 스트레스 테스트 (독립 구현 대조로 검증)
// 백트래킹이 아니라 중심 후보를 3중 루프(i < j < k)로 전부 돌리고 겹침을 좌표 쌍 비교로
// 확인하는 완전히 다른 구현을 따로 짜서 랜덤 3,000케이스(N = 6..8, 가격 0..200)와 대조
// -> 3000/3000 일치. 겹침 판정과 탐색 범위가 같음을 확인했다.

// 접근
//
// [1단계 — 유형 판별]
// 먼저 규모를 센다. 중심이 될 수 있는 칸은 (N-2)^2 로 N = 10에서도 64개뿐이고,
// 그중 3개를 고르는 조합은 C(64,3) = 41,664가지다. 한 조합을 검사하는 데 15칸을 보므로
// 60만 번 수준 — 완전탐색이 그대로 답이다(판별 로직도의 "브루트포스로 통하면 끝").
// 그리디("5칸 합이 제일 싼 꽃부터 집는다")가 그럴듯해 보이지만 반례가 있다.
// 위 반례 격자에서 그리디 23 / 최적 21 — 싼 꽃 하나가 자기보다 이득이 큰 두 자리를 동시에
// 막아 버리기 때문이다. 랜덤 탐색으로 실제 격자를 찾아 위에 적어 두었다.
// DP도 맞지 않는다 — "어디에 무엇을 놓았는가"가 곧 상태인데 15칸 배치를 표로 담을 수 없다.
//
// [2단계 — 설계]
// 중심 후보를 한 줄로 늘어놓고, 그중 3개를 고르는 조합 백트래킹이다.
// 15650 N과 M (2)의 골격 그대로 — 시작 인덱스를 넘겨 dfs(i + 1)로 내려가면
// 같은 조합을 순서만 바꿔 다시 세지 않는다.
// 상태는 격자 위 visited 한 장으로 충분하다: 꽃을 놓을 때 5칸을 1로 칠하고, 되돌릴 때 0으로 지운다.
// 놓을 수 있는지는 그 5칸이 전부 0인지만 보면 된다(겹침 판정).
// 반환값은 "여기서부터 남은 꽃을 다 놓았을 때의 최소 추가 비용"으로 두고 min으로 접는다.
//
// [3단계 — 함정]
// 1) 중심은 테두리를 뺀 안쪽만 후보다. 0행/0열/마지막 행·열에 심으면 꽃잎이 밖으로 나가 죽는다.
//    후보를 만들 때 y, x를 1 이상 N-2 이하로 잡아 두면 이후에 범위 검사가 아예 필요 없다.
// 2) 넣고/빼고를 대칭으로 맞춘다(튜터 백트래킹 템플릿). 칠한 5칸을 정확히 같은 5칸으로 지워야 하고,
//    짝이 어긋나면 다음 가지에서 남의 꽃 자국이 남아 조용히 틀린다.
// 3) 조합이므로 dfs(i + 1)이다. dfs(i)로 쓰면 같은 자리에 두 번 심으려 하고(겹침으로 걸러지긴 하지만),
//    dfs(here)를 0으로 되돌리면 같은 조합을 6번(3!) 중복 탐색한다.
// 4) 실패 경로의 반환값(INF)을 조심한다. "후보를 i부터 훑었더니 세 송이를 못 채웠다"는 가지가
//    실제로 생긴다 — 예제 입력에서 dfs 호출 139회 중 40회가 그런 가지였다(실측).
//    그 가지가 min에 끼면 안 되므로 답이 될 수 없는 큰 값을 돌려준다. 실측으로 확인한 두 오답:
//      INF = 0        -> 답 0     min(무엇이든, 0) = 0 (분석 체크리스트의 단골 결함)
//      INF = INT_MAX  -> 답 -2147483645  cost + INF 가 int를 넘어 음수가 되어 최선으로 뽑힌다
//    조건은 "답의 상한보다 크고, 거기에 5칸 값을 더해도 int를 안 넘는 값" 두 가지뿐이다.
//    그래서 1e9 같은 관습적인 큰 수 대신 상한을 그대로 적었다 — 3 x 5 x 200 + 1 = 3,001.
//    이러면 "왜 하필 그 숫자인가"에 답이 붙고, 더할 때 오버플로할 여지도 사라진다.
// 5) N >= 6이면 세 꽃을 놓을 자리는 항상 존재한다(예: 중심 (1,1), (1,4), (4,1)).
//    그래서 최종 답이 INF로 나오는 일은 없지만, 위 4)의 형태를 지키면 그 경우에도 안전하다.
//
// [4단계 — 제한과 자료형]
// 조합 41,664가지 x 검사 15칸 = 60만 번. 시간·메모리 모두 여유가 크다.
// 답의 상한은 3 x 5 x 200 = 3,000으로 int에 한참 못 미친다 — long long이 필요 없다.
// visited는 강사 관례대로 int 배열로 넉넉히(14 x 14) 전역에 잡는다.
//
// [구현 순서]  — 선언부터 순서대로. 코드의 같은 번호 주석과 1:1로 대응한다
// (1) 실패 표시 INF 상수 — "이 가지로는 세 송이를 못 놓는다"를 나타낼 값   ([3단계] 함정 4
// (2) dfs가 참조할 것을 전역으로 — 격자 a, 크기 n, 중심 후보 목록 cand
// (3) 겹침 표시용 visited + 십자 5칸을 가리키는 dy/dx (첫 칸은 중심 자신)  ([2단계] visited 한 장
// (4) 겹침 판정 canPlant — 십자 5칸이 전부 비어 있는가
// (5) 심기/뽑기 plant — v가 1이면 심고 0이면 뽑는다. 5칸 가격 합을 반환    ([3단계] 함정 2
// (6) 조합 백트래킹 dfs — 세 송이를 다 놓았으면 추가 비용 0으로 종료      ([2단계] 15650 골격
// (7) 못 채운 가지의 초기값을 INF로 둔다                                  ([3단계] 함정 4
// (8) 후보를 i부터 훑으며 넣고 -> dfs(i + 1) -> 빼고, min으로 접는다      ([3단계] 함정 3
// (9) solution — 후보 목록 만들기(테두리 제외) + visited 비우고 dfs(0, 0) ([3단계] 함정 1
//
// [트레이스 — 예제의 최적 배치]
// 중심 (1,1): 칸 (1,1)=1 (0,1)=0 (2,1)=0 (1,0)=1 (1,2)=1  합 3
// 중심 (2,3): 칸 (2,3)=1 (1,3)=1 (3,3)=0 (2,2)=1 (2,4)=1  합 4
// 중심 (4,4): 칸 (4,4)=0 (3,4)=1 (5,4)=0 (4,3)=1 (4,5)=3  합 5
// 세 꽃이 쓰는 15칸이 서로 겹치지 않고 전부 격자 안 -> 3 + 4 + 5 = 12
//
// [복잡도] 시간 O(C((N-2)^2, 3) x 15) = 최대 60만, 공간 O(N^2).
// 실측: N = 10 최대 격자(후보 64개, 조합 41,664가지)에서 solution 호출 전체 0.42ms.

#include <iostream>
#include <vector>
#include <algorithm>

using namespace std;

const int INF = 3 * 5 * 200 + 1;            // (1) 세 송이를 못 놓은 가지가 돌려줄 값.
                                            //     3송이 x 5칸 x 가격 200 = 답의 상한, 거기에 +1이면
                                            //     어떤 정상 배치보다도 크다 (1e9 같은 매직 넘버 대신 상한에서 유도)

int n;                                      // (2)
vector<vector<int>> a;
vector<pair<int, int>> cand;

int visited[14][14];                        // (3)
int dy[] = { 0, -1, 1, 0, 0 };              //     첫 칸은 중심 자신
int dx[] = { 0, 0, 0, -1, 1 };

bool canPlant(int y, int x)                 // (4)
{
    for (int d = 0; d < 5; d++)
        if (visited[y + dy[d]][x + dx[d]]) return false;

    return true;
}

int plant(int y, int x, int v)               // (5)
{
    int sum = 0;

    for (int d = 0; d < 5; d++)
    {
        visited[y + dy[d]][x + dx[d]] = v;
        sum += a[y + dy[d]][x + dx[d]];
    }

    return sum;
}

int dfs(int here, int cnt)                   // (6)
{
    if (cnt == 3) return 0;

    int ret = INF;                           // (7)

    for (int i = here; i < (int)cand.size(); i++)
    {
        int y = cand[i].first;
        int x = cand[i].second;

        if (!canPlant(y, x)) continue;

        int cost = plant(y, x, 1);                       // (8) 넣고
        ret = min(ret, cost + dfs(i + 1, cnt + 1));
        plant(y, x, 0);                                  //     빼고
    }

    return ret;
}

int solution(vector<vector<int>> prices)
{
    int answer = 0;

    a = prices;                                          // (9)
    n = a.size();

    cand.clear();
    for (int y = 1; y < n - 1; y++)
        for (int x = 1; x < n - 1; x++)
            cand.push_back(make_pair(y, x));

    for (int y = 0; y < n; y++)
        for (int x = 0; x < n; x++)
            visited[y][x] = 0;

    answer = dfs(0, 0);

    return answer;
}

// ── 로컬 실행·디버깅용 main (채점기에 제출할 땐 이 블록만 지운다) ──────────
// 함수형 문제라 파일에 진입점이 없다. 그대로 빌드하면 LNK1561(진입점 미정의)이 난다.
int main()
{
    vector<vector<int>> prices =
    {
        {1, 0, 2, 3, 3, 4},
        {1, 1, 1, 1, 1, 1},
        {0, 0, 1, 1, 1, 1},
        {3, 9, 9, 0, 1, 99},
        {9, 11, 3, 1, 0, 3},
        {12, 3, 0, 0, 0, 1}
    };

    cout << solution(prices) << endl;       // 12
}
