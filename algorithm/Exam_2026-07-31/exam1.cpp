// [모의 코딩테스트 1] 인구 이동 — BFS로 연합 찾고 평균 내기
// 같은 문제: 백준 16234 인구 이동  https://www.acmicpc.net/problem/16234
// 난이도: solved.ac 기준 Gold IV (level 12) — 2026-07-31 조회
// 표준 입력이 아니라 solution(population, L, R) 함수형으로 주어졌다.

// 문제 설명
// N x N 격자의 각 칸이 나라이고 칸 값이 그 나라의 인구수다.
// 하루 동안, 국경선을 맞댄 두 나라의 인구 차이가 L 이상 R 이하면 그 국경선을 연다.
// 열린 국경선으로 서로 이어진 나라들이 하나의 연합이 되고,
// 연합의 각 칸은 (연합 인구 합) / (연합 칸 수)로 바뀐다(정수 나눗셈, 소수점 버림).
// 하루가 끝나면 국경선을 전부 닫는다. 더 이상 이동이 없을 때까지 반복하고, 며칠 걸렸는지 반환한다.

// 제약 조건
// 1 <= N <= 50          (칸 수 최대 2,500)
// 0 <= population[r][c] <= 100
// 1 <= L <= R <= 100    (L이 1 이상이라 인구 차 0인 국경선은 절대 안 열린다)
// 인구 이동 일수 <= 2,000 (문제가 보장 — 종료 조건을 따로 증명하지 않아도 된다)

// 예제
// population                                L   R   result
// [[50,30],[20,40]]                         20  50  1      네 칸이 한 연합 -> 전부 140/4 = 35, 다음 날은 차이 0
// [[50,30],[20,40]]                         40  50  0      차이가 10/20/20/10뿐이라 첫날부터 열리는 국경선이 없다
// [[10,15,20],[20,30,25],[40,22,10]]        5   10  2      이틀 진행

// 자체 검증 케이스 (전부 실측 통과)
// [[1]]                            1 100  0    N=1 최소 입력 — 인접 칸 자체가 없다 (BFS가 한 칸 연합으로 끝나는 경계)
// [[0,100],[100,0]]                1 100  1    최대/최소 인구 극단 — 4칸 전부 50이 되고 종료
// [[10,10],[10,10]]                1 100  0    전부 동일 — 차이 0이라 L>=1에서 영원히 안 열린다
// [[1,2],[2,1]]                    1 1    1    L=R 경계 — 차이가 정확히 1일 때만 열림. 합 6/4 = 1(내림)
// [[1,50],[50,2]]                  1 1    0    대각선은 인접이 아님을 찌르는 케이스 —
//                                              상하좌우 차는 48/49뿐이고 차가 1인 쌍은 대각선(1↔2)뿐.
//                                              8방향으로 잘못 짜면 여기서 1이 나온다
// 50x50 값 다양                    1 100  1    최대 격자 성능 — 한 번에 전부 한 연합
// 50x50 체스판 0/100               1 100  1    연합이 격자 전체로 퍼지는 최악 BFS 형태

// 스트레스 테스트 (독립 구현 대조로 검증)
// 연합을 BFS가 아니라 "인접 칸 쌍을 union-find로 합치기"로 구한 완전 별개 구현을 따로 짜서
// 랜덤 5,000케이스(N = 1..5, 인구 0..12, L·R 임의)와 대조 -> 5000/5000 일치
// (그중 실제로 이동이 일어난 케이스 3,028개, 최대 18일짜리까지 포함).
// 연합을 나누는 규칙(도달 가능성)과 평균 내림 처리가 문제 규칙과 같음을 확인했다.

// 접근
//
// [1단계 — 유형 판별]
// "하루"의 정의가 그대로 알고리즘이다. 최적화할 선택지가 없으니 DP도 그리디도 아니고,
// 시뮬레이션 + 연결 요소 찾기다. 연결 요소를 찾는 도구는 BFS/DFS/유니온 파인드인데,
// 여기서는 격자 4방향 탐색이라 BFS 골격이 그대로 들어맞는다.
// 규모 계산: 하루에 격자 전체를 한 번 훑으므로 2,500칸, 최대 2,000일 -> 500만 번.
// 완전탐색이 곧 정답이고 시간도 충분하다 (판별 로직도의 "브루트포스로 통하면 그대로 끝").
//
// [2단계 — 설계]
// 하루 = (visited 초기화) -> (모든 칸을 훑으며 안 본 칸에서 BFS) -> (연합마다 평균 대입).
// BFS 확장 조건이 이 문제의 전부다: 인접 칸이면서 |인구 차| 가 L 이상 R 이하.
// 국경선을 실제로 열고 닫는 자료구조를 만들 필요가 없다 — 매번 조건을 그 자리에서 계산하면
// "오늘 열린 국경선"과 완전히 같다.
// 하루의 종료 판정: 그날 만든 연합 중 칸이 2개 이상인 것이 하나도 없으면 이동이 없었던 날 -> 종료.
//
// [3단계 — 함정]
// 1) visited는 하루마다 리셋한다. "모든 국경선을 닫는다"가 코드에서는 이 초기화 한 줄이다.
// 2) 연합을 찾는 것과 평균을 대입하는 것을 섞으면 안 된다. BFS 도중에 값을 바꾸면
//    아직 안 본 이웃과의 인구 차가 달라져 같은 날의 판정이 오염된다.
//    연합의 칸 좌표를 모아 두었다가 BFS가 끝난 뒤에 한꺼번에 대입한다.
// 3) 평균은 내림(정수 나눗셈). sum / cnt 를 int 로 하면 그대로 내림이라 별도 처리가 없다.
//    다만 cnt 를 size() 그대로 쓰면 unsigned 와 섞이므로 int 로 받아 나눈다.
// 4) 대각선은 인접이 아니다. dy/dx 4방향만.
// 5) 스켈레톤에 있는 입출력 가속 3줄은 이 문제에서 cin/cout 을 쓰지 않아 아무 효과가 없다.
//    (표준 입력 형식이면 필요하지만 함수형 채점에서는 무의미 — 원본 스켈레톤 그대로 남겨 둔다.)
//
// [4단계 — 제한과 자료형]
// 하루 O(N^2) 스캔 + BFS 총합도 O(N^2). 2,000일 x 2,500칸 = 500만 번으로 넉넉하다.
// 연합 인구 합의 상한은 2,500칸 x 100명 = 250,000으로 int(21억)에 한참 못 미친다 — long long 불필요.
// visited는 강사 관례대로 int 배열 54x54로 여유를 두고 전역에 잡는다.
//
// [구현 순서]  — 선언부터 순서대로. 코드의 같은 번호 주석과 1:1로 대응한다
// (1) BFS가 참조할 값을 전역으로 — 격자 a, 크기 n, 기준 L·R              ([2단계] BFS를 함수로 뺐으므로
// (2) 연합 표시용 visited + 상하좌우를 가리키는 dy/dx                     ([3단계] 함정 4 (대각선 제외)
// (3) BFS — 연합 하나를 찾아 좌표를 모으고 칸 수를 반환                   ([2단계] 연결 요소
// (4) 확장 조건: 격자 안 + 미방문 + |인구 차|가 L 이상 R 이하             ([2단계] 이 문제의 핵심 한 줄
// (5) BFS가 끝난 뒤 모아 둔 좌표에 평균을 한꺼번에 대입 (내림 나눗셈)     ([3단계] 함정 2, 3
// (6) 하루 루프 — visited를 통째로 0으로 = "모든 국경선을 닫는다"         ([3단계] 함정 1
// (7) 격자 전 칸 스캔, 아직 안 본 칸마다 BFS 한 번 = 연합 하나
// (8) 칸 2개 이상 연합이 하나라도 있었으면 answer++, 없으면 루프 종료     ([2단계] 종료 판정
//
// [트레이스 — 예제 3 (L = 5, R = 10)]
// 초기        10 15 20 / 20 30 25 / 40 22 10
// 1일차 연합  (0,0)(0,1)(0,2)(1,0)(1,1)(1,2)(2,1) 이 하나로 이어진다 (예: |10-15|=5 열림, |20-30|=10 열림)
//             합 10+15+20+20+30+25+22 = 142, 칸 7개 -> 142/7 = 20 (내림)
//             (2,0)=40 은 이웃 20 과 차 20 > R, 22 와 차 18 > R 이라 혼자. (2,2)=10 도 혼자.
//             결과 20 20 20 / 20 20 20 / 40 20 10
// 2일차       (2,2)=10 과 위쪽 20 의 차가 10 = R 이라 열린다 -> 20 무리 8칸 + 10 이 한 연합
//             합 20*7 + 10 = 150, 칸 8개 -> 150/8 = 18 (내림). 40 은 차 22 로 여전히 혼자
//             결과 18 18 18 / 18 18 18 / 40 18 18
// 3일차       18끼리는 차 0, 40 과 18 은 차 22 > R -> 열리는 국경선 없음 -> 종료
// 반환 2
//
// [복잡도] 시간 O(일수 x N^2) = 최대 500만, 공간 O(N^2).
// 실측: 50x50 체스판(0/100) 입력에서 solution 호출 전체 0.36ms.

#include <iostream>
#include <vector>
#include <cmath>
#include <queue>
#include <algorithm>

using namespace std;

int n, lo, hi;                  // (1)
vector<vector<int>> a;

int visited[54][54];            // (2)
int dy[] = { -1, 1, 0, 0 };     //     상하좌우 4방향만 — 대각선은 인접이 아니다
int dx[] = { 0, 0, -1, 1 };

int bfs(int y, int x)           // (3)
{
    queue<pair<int, int>> q;
    vector<pair<int, int>> group;

    q.push(make_pair(y, x));
    visited[y][x] = 1;
    int sum = 0;

    while (!q.empty())
    {
        int cy = q.front().first;
        int cx = q.front().second;
        q.pop();

        group.push_back(make_pair(cy, cx));
        sum += a[cy][cx];

        for (int i = 0; i < 4; i++)                     // (4)
        {
            int ny = cy + dy[i];
            int nx = cx + dx[i];

            if (ny < 0 || ny >= n || nx < 0 || nx >= n) continue;
            if (visited[ny][nx]) continue;

            int diff = abs(a[cy][cx] - a[ny][nx]);
            if (diff < lo || diff > hi) continue;

            visited[ny][nx] = 1;
            q.push(make_pair(ny, nx));
        }
    }

    int cnt = group.size();                             // (5)
    int avg = sum / cnt;
    for (auto& p : group)
        a[p.first][p.second] = avg;

    return cnt;
}

int solution(vector<vector<int>> population, int L, int R)
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);
    int answer = 0;

    a = population;                                     // (1)
    n = a.size();
    lo = L;
    hi = R;

    while (true)
    {
        for (int y = 0; y < n; y++)                     // (6)
            for (int x = 0; x < n; x++)
                visited[y][x] = 0;

        int moved = 0;

        for (int y = 0; y < n; y++)                     // (7)
            for (int x = 0; x < n; x++)
                if (!visited[y][x])
                    if (bfs(y, x) >= 2) moved = 1;

        if (!moved) break;                              // (8)
        answer++;
    }

    return answer;
}

// ── 로컬 실행·디버깅용 main (채점기에 제출할 땐 이 블록만 지운다) ──────────
// 함수형 문제라 파일에 진입점이 없다. 그대로 빌드하면 LNK1561(진입점 미정의)이 난다.
int main()
{
    cout << solution({ {50,30},{20,40} }, 20, 50) << endl;                  // 1
    cout << solution({ {50,30},{20,40} }, 40, 50) << endl;                  // 0
    cout << solution({ {10,15,20},{20,30,25},{40,22,10} }, 5, 10) << endl;  // 2
    cout << solution({ {1,50},{50,2} }, 1, 1) << endl;                      // 0 (대각선은 인접 아님)
}
