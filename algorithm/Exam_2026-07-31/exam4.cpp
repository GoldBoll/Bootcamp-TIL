// [모의 코딩테스트 4] 수학숙제 — 문자열에서 수를 뽑아 수의 크기로 정렬
// 같은 문제: 백준 2870 수학숙제  https://www.acmicpc.net/problem/2870
// 난이도: solved.ac 기준 Silver IV (level 7) — 2026-07-31 조회.
//         네 문제 중 가장 낮지만 함정 밀도는 제일 높다 — 자릿수가 100까지라 수로 바꿀 수 없다

// 문제 설명
// 소문자와 숫자로 이루어진 문자열 여러 줄이 주어진다. 각 줄에서 숫자를 전부 찾되,
// 숫자는 "가능한 가장 큰 것"으로 잡는다 — 즉 연속된 숫자 덩어리 하나가 수 하나다.
// 앞에 붙은 0은 생략한다(01 -> 1, 00 -> 0). 찾은 수들을 비내림차순으로 정렬해 반환한다.

// 제약 조건
// 줄 수 1 <= n <= 100
// 각 줄 길이 1 <= len <= 100
// 문자는 소문자와 숫자뿐 (부호·공백 없음)
// 한 수의 자릿수는 최대 100자리 -> long long(19자리)으로 절대 못 담는다
// 수의 최대 개수는 숫자와 문자가 번갈아 나올 때로 한 줄에 50개, 전체 5,000개

// 예제
// papers                                                  result
// ["lo3za4", "01"]                                        ["1","3","4"]
// ["43silos0", "zita002", "le2sim", "231233"]             ["0","2","2","43","231233"]
// ["01bond", "02james007", "03bond", "04austinpowers000"] ["0","1","2","3","4","7"]

// 자체 검증 케이스 (전부 실측 통과)
// ["abc"]                        []                    숫자가 하나도 없는 줄 — 빈 배열 반환
// ["0"]                          ["0"]                 최소 입력. 0을 지우면 안 되는 유일한 경우
// ["000"]                        ["0"]                 전부 0 — 앞의 0을 지우다 빈 문자열이 되는 함정
// ["9a10"]                       ["9","10"]            사전순으로 정렬하면 10이 9보다 앞에 온다 (반례)
// ["1a1a1"]                      ["1","1","1"]         같은 수 중복 — 중복 제거하면 안 된다
// ["100...0"] (1 뒤에 0이 99개)  그대로 100자리        long long 불가를 확인하는 최대 자릿수
// ["0000...0"] (0이 100개)       ["0"]                 최대 길이가 전부 0
// 100줄 x 100자 숫자·문자 교대   5,000개               최대 개수 (성능 측정용)

// 스트레스 테스트 (독립 구현 대조로 검증)
// 완전히 다른 방식의 구현을 따로 짜서 대조했다 — 추출은 정규식(regex "[0-9]+"),
// 정렬은 "두 수를 같은 길이가 되도록 앞에 0을 채운 뒤 사전순 비교"로 구현.
// 랜덤 3,000케이스(1~4줄, 각 줄 1~12자, 숫자 비율을 높여 덩어리가 자주 생기게)와 대조
// -> 3000/3000 일치 (수가 하나 이상 뽑힌 케이스 2,969개).
// 추출 경계(줄 끝에서 끊기는 덩어리)와 정렬 기준이 모두 같음을 확인했다.

// 접근
//
// [1단계 — 유형 판별]
// 탐색도 최적화도 없다. 규칙을 그대로 옮기는 문자열 처리 + 정렬 문제다.
// 어려움은 알고리즘이 아니라 두 지점에 있다:
//   (가) 무엇이 "한 수"인가 — 연속된 숫자 덩어리 전체. 한 글자씩 보면 안 된다
//   (나) 어떻게 크기를 비교하는가 — 100자리라 수로 바꿀 수 없다
// 전체 문자 수가 100 x 100 = 10,000자뿐이라 한 번 훑는 것으로 충분하다.
//
// [2단계 — 설계]
// 각 줄을 왼쪽부터 훑다가 숫자를 만나면, 숫자가 아닌 문자(또는 줄 끝)를 만날 때까지 밀어
// 그 구간 전체를 수 하나로 잘라 낸다. 이것이 "가능한 가장 큰 숫자"의 정의 그대로다.
// 잘라 낸 뒤 앞의 0을 지우되 **마지막 한 자리는 남긴다** — 그래야 "000"이 ""가 아니라 "0"이 된다.
// 정렬 기준은 수의 크기다. 문자열이지만 두 수 다 앞의 0이 없으므로:
//   자릿수가 다르면 짧은 쪽이 작다. 자릿수가 같으면 사전순이 곧 크기순이다.
// 이 두 줄이 cmp 함수의 전부다.
//
// [3단계 — 함정]
// 1) 그냥 sort하면 사전순이라 틀린다. "10"과 "9"를 비교하면 '1' < '9'라 10이 앞에 온다.
//    자릿수를 1차 기준으로 두는 cmp가 필요하다 (1931에서 굳힌 "기준은 cmp에 명시").
// 2) 앞의 0을 while로 지울 때 조건을 num[p] == '0' 만으로 두면 "000"에서 전부 지워져
//    빈 문자열이 남는다. p + 1 < 길이 를 같이 걸어 마지막 한 자리를 보존한다.
// 3) 숫자 덩어리를 만나면 그 끝까지 건너뛰어야 한다. 안 그러면 "3456"에서
//    3456, 456, 56, 6 이 전부 뽑힌다. 바깥 루프 인덱스를 j - 1로 밀어 두고 i++에 맡긴다.
// 4) 줄 끝에서 끝나는 덩어리("...478")를 놓치기 쉽다. while 조건에 j < 길이를 먼저 두면
//    자연히 처리된다.
// 5) 중복은 제거하지 않는다. 예제 2의 "2"처럼 같은 수가 여러 번 나오면 그대로 다 담는다.
// 6) 숫자 판별에 isdigit 대신 c >= '0' && c <= '9' 를 쓴다. 강사 관례의 c - '0' 계열과 같은 결이고
//    <cctype> 추가나 char 부호 문제를 신경 쓸 필요가 없다.
//
// [4단계 — 제한과 자료형]
// 전체 문자 10,000자를 한 번 훑는다. 수는 최대 5,000개, 정렬은 5,000 log 5,000에
// 비교마다 최대 100자 비교라도 여유가 크다.
// **자료형이 이 문제의 핵심이다.** 자릿수가 최대 100이라 long long(약 19자리)은 물론
// unsigned long long, __int128(약 38자리)도 못 담는다. 반환형이 vector<string>인 것이
// 출제자가 "수로 바꾸지 말고 문자열로 비교하라"고 알려 주는 신호다.
//
// [구현 순서]  — 선언부터 순서대로. 코드의 같은 번호 주석과 1:1로 대응한다
// (1) 숫자 판별 isNum — isdigit 대신 범위 비교                             ([3단계] 함정 6
// (2) 정렬 기준 cmp — 자릿수 우선, 같으면 사전순 (이것이 곧 수의 크기순)   ([3단계] 함정 1
// (3) 줄마다 왼쪽부터 훑으며 숫자가 아닌 문자는 건너뛴다
// (4) 숫자를 만나면 숫자가 끝나는 위치 j까지 밀어 덩어리 전체를 잘라 낸다  ([2단계] "가장 큰 숫자"
// (5) 앞의 0을 지우되 마지막 한 자리는 남긴다 (000 -> 0)                   ([3단계] 함정 2
// (6) 바깥 인덱스를 덩어리 끝으로 옮겨 같은 덩어리를 다시 읽지 않게 한다   ([3단계] 함정 3
// (7) cmp로 정렬해 반환
//
// [트레이스 — 예제 2의 "43silos0" 과 "zita002"]
// "43silos0"  i=0 '4' 숫자 -> j를 밀어 j=2("43"), 앞의 0 없음 -> "43" 담기, i를 1로 옮김(i++ -> 2)
//             i=2..6 's','i','l','o','s' 건너뜀
//             i=7 '0' 숫자 -> j=8(줄 끝) -> "0", 앞의 0을 지우려 하지만 p+1 < 1 이 거짓이라 그대로 "0"
// "zita002"   i=0..3 문자 건너뜀
//             i=4 '0' -> j=7(줄 끝) -> "002", p를 밀어 앞의 0 두 개 제거 -> "2"
// 모인 것: "43" "0" "2" "2" "231233"
// 정렬: 자릿수 1인 "0","2","2" 가 먼저(사전순), 그다음 2자리 "43", 마지막 6자리 "231233"
// 결과 ["0","2","2","43","231233"]
//
// [복잡도] 시간 O(전체 문자 수 + K log K x 자릿수), 공간 O(전체 문자 수). K는 수의 개수(<= 5,000).
// 실측: 100줄 x 100자 최대 입력에서 수 5,000개를 뽑아 정렬까지 solution 호출 전체 0.29ms.
// 최대 자릿수 확인: ["1" + "0" x 99, "0" x 100] -> ["0", 100자리 수] 로 자릿수가 보존된다.

#include <iostream>
#include <vector>
#include <string>
#include <algorithm>

using namespace std;

bool isNum(char c)                              // (1)
{
    return c >= '0' && c <= '9';
}

bool cmp(const string& a, const string& b)      // (2)
{
    if (a.size() == b.size())
        return a < b;

    return a.size() < b.size();
}

vector<string> solution(vector<string> papers)
{
    vector<string> answer;

    for (string& s : papers)
    {
        int len = s.size();

        for (int i = 0; i < len; i++)                   // (3)
        {
            if (!isNum(s[i])) continue;

            int j = i;
            while (j < len && isNum(s[j])) j++;          // (4)

            string num = s.substr(i, j - i);

            int p = 0;
            while (p + 1 < (int)num.size() && num[p] == '0') p++;   // (5)

            answer.push_back(num.substr(p));

            i = j - 1;                                   // (6)
        }
    }

    sort(answer.begin(), answer.end(), cmp);             // (7)

    return answer;
}

// ── 로컬 실행·디버깅용 main (채점기에 제출할 땐 이 블록만 지운다) ──────────
// 함수형 문제라 파일에 진입점이 없다. 그대로 빌드하면 LNK1561(진입점 미정의)이 난다.
int main()
{
    vector<vector<string>> tests =
    {
        { "lo3za4", "01" },                                        // 1 3 4
        { "43silos0", "zita002", "le2sim", "231233" },             // 0 2 2 43 231233
        { "01bond", "02james007", "03bond", "04austinpowers000" }, // 0 1 2 3 4 7
        { "abc" },                                                 // (빈 줄)
        { "000" },                                                 // 0
        { "9a10" }                                                 // 9 10
    };

    for (vector<string>& t : tests)
    {
        for (string& num : solution(t))
            cout << num << " ";

        cout << endl;
    }
}
