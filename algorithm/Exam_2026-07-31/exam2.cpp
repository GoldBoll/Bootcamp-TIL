// [모의 코딩테스트 2] 순회강연 — 기한 있는 작업 스케줄링 (그리디 + 최소 힙)
// 같은 계열: 백준 1781 컵라면  https://www.acmicpc.net/problem/1781
// 난이도: solved.ac 기준 Gold II (level 14) — 2026-07-31 조회.
//         세 문제 중 가장 높다. 그리디 기준 자체보다 "왜 그 기준이 최적인가"를 대는 쪽이 어렵다

// 문제 설명
// n개 대학이 "d일 안에 와서 강연하면 p를 주겠다"고 제안했다.
// 하루에 한 곳에서만 강연할 수 있고, 강연은 기한 d일째까지 아무 날에나 해도 된다.
// 벌 수 있는 돈의 최댓값을 구한다. requests의 원소는 [p, d] 순서다.

// 제약 조건
// 0 <= n <= 10,000        (n = 0이면 답은 0)
// 1 <= p <= 10,000
// 1 <= d <= 10,000
// 선택할 수 있는 강연 수의 상한은 min(n, 최대 기한) = 10,000

// 예제
// requests                                                    result
// [[20,1],[2,1],[10,3],[100,2],[8,2],[5,20],[50,10]]          185
//   기한 1에서 20, 기한 2에서 100, 기한 3에서 10, 여유 있는 50과 5까지 -> 185

// 자체 검증 케이스 (전부 실측 통과)
// []                                    0            n = 0 최소 입력 — 루프 미실행 경로
// [[10000,1]]                           10000        원소 1개 · p 최댓값
// [[5,1],[10,1],[3,1]]                  10           기한이 같아 하루뿐 — 가장 비싼 것 하나만
// [[1,10000]]                           1            기한 최댓값 — 여유가 남아도 답은 그대로
// [[100,1],[99,1],[1,2]]                101          비싼 것 둘이 같은 날을 다투는 경우.
//                                                    99를 버리고 1을 살려야 이득이 커진다
// [[1,1],[2,2],[3,3],[4,4]]             10           전부 선택 가능 — 아무것도 안 버린다
// [[10,2],[20,2],[30,2],[40,2]]         70           기한 2에 넷이 몰림 — 상위 두 개만
// 10,000개 전부 [10000,10000]           100000000    답의 상한(10^8) — int 한계 안에 드는지 확인
// 10,000개 랜덤 p·d                     (성능 측정용)

// 스트레스 테스트 (독립 구현 대조로 검증)
// 부분집합을 전부 만들어 보는 완전탐색(고른 강연을 기한순으로 세워 i번째가 기한 i 이하인지 검사,
// 실현 가능한 집합 중 최대 합)을 따로 구현해 랜덤 3,000케이스(n = 0..8, p 1..20, d 1..5)와 대조
// -> 3000/3000 일치 (기한 경합이 실제로 일어나는 n >= 4 케이스 1,622개 포함).
// 그리디 선택 기준이 실제 최적해와 같음을 확인했다.

// 접근
//
// [1단계 — 유형 판별]
// 완전탐색: 각 강연을 넣거나 빼는 2^n 부분집합. n = 10,000이면 논외다.
// DP도 어색하다 — "며칠째에 무엇을 했는가"를 상태로 잡으면 10,000일 x 선택 조합이라
// 표에 담기지 않는다 (판별 로직도의 "배열에 담기지 않으면 그리디").
// 그럼 어떤 기준으로 고를 것인가. 두 가지 그럴듯한 기준이 있다:
//   (가) 강연료가 비싼 것부터 골라 가능한 한 늦은 빈 날에 배치한다
//   (나) 기한이 이른 것부터 훑으며 일단 다 잡고, 넘치면 가장 싼 것을 버린다
// 둘 다 정답이지만 (가)는 "빈 날 찾기"에 유니온 파인드가 필요하고,
// (나)는 정렬 + 최소 힙만으로 끝난다. 후보가 단계마다 늘어나며 최솟값을 빼야 하므로
// 우선순위 큐를 쓰는 1202 보석 도둑의 짝 구조다(거기선 최댓값을 꺼냈고 여기선 최솟값을 버린다).
//
// [2단계 — 설계 (기준과 정당성)]
// 기한 오름차순으로 훑으며, 지금까지 고른 강연을 최소 힙에 담는다.
//   1) 현재 강연을 일단 무조건 힙에 넣는다.
//   2) 힙 크기가 현재 기한 d를 넘으면 가장 싼 강연 하나를 버린다.
// 왜 맞는가: 기한을 오름차순으로 처리하면 "기한이 t 이하인 강연을 t개 넘게 고를 수 없다"는
// 조건만 지키면 실제 날짜 배정이 항상 가능하다(빠른 기한부터 앞날에 채우면 된다).
// 크기가 넘칠 때 버리는 것이 가장 싼 것이어야 손해가 최소이고, 지금 버린 것이 나중에
// 다시 필요해지는 일은 없다 — 이후 강연들은 기한이 더 길어 제약이 느슨해지기만 하기 때문이다.
//
// [3단계 — 함정]
// 1) 입력이 [p, d] 순서다. 기한은 원소[1]이다. 그냥 sort하면 강연료 기준으로 정렬돼 전부 틀린다.
//    1931에서 배운 대로 뒤집어 담는 대신 cmp 함수에 "a[1] < b[1]"로 기준을 명시한다.
// 2) 힙은 최소 힙이어야 한다. priority_queue의 기본은 최대 힙이라 그대로 쓰면
//    가장 비싼 강연을 버리게 되어 정반대로 동작한다 -> greater<int> 지정.
// 3) 기한이 같은 강연들 사이의 2차 정렬 기준은 필요 없다. 같은 기한끼리 순서를 바꿔도
//    "일단 넣고 넘치면 최솟값을 버린다"의 결과 집합이 같다(그리디 셀프 체크리스트 1의 상태 중립).
// 4) pq.size()는 unsigned다. d와 비교할 때 int로 캐스팅해 부호 혼합 경고를 없앤다.
// 5) cmp의 인자는 const 참조로 받는다. 튜터 코드처럼 pair를 값으로 받는 건 싸지만,
//    vector<int>를 값으로 받으면 비교마다 벡터를 복사한다.
//
// [4단계 — 제한과 자료형]
// 정렬 O(n log n) + 원소마다 힙 연산 O(log n) = 10,000 x 14 수준. 시간은 문제되지 않는다.
// 답의 상한은 (고를 수 있는 최대 개수 10,000) x (p 최댓값 10,000) = 10^8 이다.
// int 상한 약 2.1 x 10^9의 20분의 1이라 int로 충분하다 — long long을 쓸 이유가 없다.
// (반환형이 int인 것도 출제자가 int로 충분함을 전제했다는 신호다.)
//
// [구현 순서]  — 선언부터 순서대로. 코드의 같은 번호 주석과 1:1로 대응한다
// (1) 정렬 기준 cmp — 기한은 원소[1]. 여기서 틀리면 전부 틀린다          ([3단계] 함정 1, 5
// (2) 기한 오름차순 정렬                                                 ([2단계] 처리 순서
// (3) 선택한 강연료를 담을 최소 힙 준비 (greater<int>)                   ([3단계] 함정 2
// (4) 정렬 순서대로 현재 강연을 일단 무조건 넣는다                       ([2단계] 규칙 1
// (5) 힙 크기가 현재 기한을 넘으면 가장 싼 강연 하나를 버린다            ([2단계] 규칙 2
// (6) 힙에 남은 강연료를 전부 더해 반환 (n = 0이면 루프를 안 돌아 0)     ([4단계] int로 충분
//
// [트레이스 — 예제]
// 기한 오름차순 정렬: [20,1] [2,1] [100,2] [8,2] [10,3] [50,10] [5,20]
//   [20,1]   push 20   힙 {20}          크기 1 <= 1
//   [2,1]    push 2    힙 {2,20}        크기 2 > 1  -> 최솟값 2 버림  {20}
//   [100,2]  push 100  힙 {20,100}      크기 2 <= 2
//   [8,2]    push 8    힙 {8,20,100}    크기 3 > 2  -> 최솟값 8 버림  {20,100}
//   [10,3]   push 10   힙 {10,20,100}   크기 3 <= 3
//   [50,10]  push 50   힙 {10,20,50,100}            크기 4 <= 10
//   [5,20]   push 5    힙 {5,10,20,50,100}          크기 5 <= 20
// 합 5 + 10 + 20 + 50 + 100 = 185
//
// [복잡도] 시간 O(n log n), 공간 O(n).
// 실측: n = 10,000 랜덤 입력에서 solution 호출 전체 2.1ms.

#include <iostream>
#include <vector>
#include <queue>
#include <algorithm>

using namespace std;

bool cmp(const vector<int>& a, const vector<int>& b)    // (1)
{
    return a[1] < b[1];                                 //     [1]이 기한 d, [0]은 강연료 p
}

int solution(vector<vector<int>> requests)
{
    int answer = 0;

    sort(requests.begin(), requests.end(), cmp);            // (2)

    priority_queue<int, vector<int>, greater<int>> pq;      // (3)

    for (auto& r : requests)
    {
        pq.push(r[0]);                                      // (4)

        if ((int)pq.size() > r[1])                          // (5)
            pq.pop();
    }

    while (pq.size())                                       // (6)
    {
        answer += pq.top();
        pq.pop();
    }

    return answer;
}

// ── 로컬 실행·디버깅용 main (채점기에 제출할 땐 이 블록만 지운다) ──────────
// 함수형 문제라 파일에 진입점이 없다. 그대로 빌드하면 LNK1561(진입점 미정의)이 난다.
int main()
{
    cout << solution({ {20,1},{2,1},{10,3},{100,2},{8,2},{5,20},{50,10} }) << endl;  // 185
    cout << solution({}) << endl;                                                    // 0
    cout << solution({ {5,1},{10,1},{3,1} }) << endl;                                // 10
    cout << solution({ {100,1},{99,1},{1,2} }) << endl;                              // 101
}
