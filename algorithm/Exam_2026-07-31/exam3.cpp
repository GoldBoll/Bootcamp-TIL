// [모의 코딩테스트 3] 용돈 관리 — 답을 이분 탐색한다 (매개변수 탐색)
// 같은 문제: 백준 6236 용돈 관리  https://www.acmicpc.net/problem/6236
// 난이도: solved.ac 기준 Silver I (level 10) — 2026-07-31 조회.
//         세 문제 중 가장 낮지만, 매개변수 탐색을 모르면 티어와 무관하게 손도 못 댄다

// 문제 설명
// N일 동안 매일 정해진 금액을 쓴다. 통장에서 정확히 M번만 인출하는데, 한 번에 항상 K원을 뽑는다.
// 가진 돈으로 그날을 보낼 수 있으면 쓰고, 모자라면 남은 돈을 통장에 넣고 다시 K원을 뽑는다.
// 인출 횟수가 M보다 적게 나오면 남아도 일부러 다시 뽑아 M번을 맞출 수 있다고 가정한다.
// 가능한 K의 최솟값을 구한다.

// 제약 조건
// 1 <= N <= 100,000
// 1 <= M <= N
// 1 <= 하루 사용 금액 <= 10,000
// 총합의 상한 = 100,000일 x 10,000원 = 1,000,000,000 (10^9)

// 예제
// money_list                                  M   result
// [100,400,300,100,500,101,400]               5   500
//   K = 500이면 5번 인출로 7일을 보낼 수 있고, 그보다 작으면 5일차(500원)를 못 넘긴다

// 자체 검증 케이스 (전부 실측 통과)
// [10000], 1                          10000        N = 1 최소 입력 (탐색 구간이 한 점 [10000,10000])
// [1,2,3], 3                          3            M = N — 매일 뽑을 수 있으니 답은 하루 최댓값
// [100,400,300,100,500,101,400], 1    1901         M = 1 — 한 번에 다 뽑아야 하므로 답은 총합
// [100,400,300,100,500,101,400], 3    800          답이 하루 최댓값(500)보다 커지는 경우.
//                                                  예제(M=5)는 답이 곧 최댓값이라 이분 탐색이
//                                                  움직이는지 확인이 안 돼서 따로 둔 케이스
// [5,5,5,5], 2                        10           균등 분할이 딱 떨어지는 경우
// 100,000일 전부 10000, 100000        10000        최대 N에서 M = N (매일 인출)
// 100,000일 전부 10000, 1             1000000000   답의 상한 10^9 — int 안에 드는지 확인하는 케이스
// 100,000일 랜덤, M = 300             (성능 측정용)

// 스트레스 테스트 (독립 구현 대조로 검증)
// 이분 탐색 대신 K를 하루 최댓값부터 총합까지 1씩 올려 보며 조건을 만족하는 첫 값을 찾는
// 완전탐색을 따로 구현해 랜덤 4,000케이스(N = 1..8, 금액 1..15, M = 1..N)와 대조
// -> 4000/4000 일치 (답이 하루 최댓값보다 커서 탐색이 실제로 움직인 케이스 2,064개 포함).
// 판정 함수와 "가능/불가능의 경계"가 실제 최솟값과 같음을 확인했다.

// 접근
//
// [1단계 — 유형 판별]
// K를 1부터 올려 보며 되는지 확인하는 완전탐색은 K의 후보가 최대 10^9개라 그대로는 안 된다.
// 그런데 이 문제는 "최솟값을 구하라"인데 답을 직접 계산하는 식이 없다.
// 대신 **K를 하나 정해 주면 되는지 안 되는지는 O(N)에 판정할 수 있다**(하루씩 시뮬레이션).
// 그리고 K가 커질수록 인출 횟수는 줄기만 한다 — 돈을 더 많이 들고 시작하면 매 시점의 잔액이
// 더 크거나 같아 다시 뽑아야 하는 날이 늘어날 수 없다.
// 즉 K축에서 [불가능 ... 불가능 | 가능 ... 가능] 으로 한 번만 뒤집히므로 경계를 이분 탐색한다.
// (답 자체를 이분 탐색하는 매개변수 탐색. 완전탐색 10^9 -> 판정 O(N) x log(10^9) = 30번)
//
// [2단계 — 설계]
// 판정 함수 countWithdraw(K) = K원씩 뽑아 쓸 때 실제로 필요한 인출 횟수.
//   첫날 한 번 뽑고 시작(cnt = 1, cur = K), 하루씩 보며 잔액이 그날 금액보다 적으면
//   다시 뽑는다(cnt++, cur = K). 그날 금액을 잔액에서 뺀다.
// K가 가능하다 <=> countWithdraw(K) <= M.
//   "정확히 M번"인데 부등호인 이유는, 덜 뽑았으면 남은 돈을 넣었다 다시 뽑는 헛인출로
//   횟수를 채울 수 있다고 문제가 보장하기 때문이다. == M 으로 쓰면 틀린다.
// 탐색 구간:
//   lo = 하루 사용 금액의 최댓값 — 그보다 작으면 그날 하루를 아예 못 넘긴다(불가능 구간을 미리 잘라 낸다)
//   hi = 전체 합 — 한 번에 다 뽑는 경우로 항상 가능하다(M >= 1이므로)
//
// [3단계 — 함정]
// 1) lo를 1로 잡으면 안 된다. K < 하루 최댓값이면 그날 잔액을 다시 채워도 여전히 모자라
//    판정 함수가 무한히 뽑거나(구현에 따라) 엉뚱한 답을 낸다.
//    lo = 최댓값으로 두면 "다시 뽑으면 항상 그날은 넘긴다"가 보장돼 판정 함수가 단순해진다.
// 2) mid = (lo + hi) / 2 로 쓰지 않는다. hi가 10^9까지 가므로 lo + hi가 2 x 10^9으로
//    int 상한(약 2.147 x 10^9)에 7% 차이까지 붙는다. 지금 제약에선 넘치지 않지만
//    제약이 조금만 커져도 바로 오버플로다. mid = lo + (hi - lo) / 2 로 쓴다.
// 3) 조건은 <= M 이지 == M 이 아니다([2단계] 참고).
// 4) "가능"일 때 답을 기록하고 hi = mid - 1로 더 줄여 본다. 기록 없이 루프를 빠져나온 lo를
//    그대로 쓰는 판본도 있지만, 답을 그때그때 잡아 두는 편이 경계 실수에 강하다.
//
// [4단계 — 제한과 자료형]
// 판정 O(N) x 이분 탐색 log2(10^9) 약 30회 = 300만 번. 넉넉하다.
// 답의 상한은 총합 10^9으로 int 상한 2.147 x 10^9 안에 든다 — long long이 필요 없다.
// accumulate의 초기값도 0(int)으로 두면 int로 누적되는데, 10^9까지라 안전하다.
// (하루 금액이나 N의 상한이 커지면 이 두 곳이 동시에 위험해지는 자리다.)
//
// [구현 순서]  — 선언부터 순서대로. 코드의 같은 번호 주석과 1:1로 대응한다
// (1) 판정 함수가 참조할 일별 금액을 전역으로                              ([2단계] 판정을 함수로 뺐으므로
// (2) 판정 함수 countWithdraw — K로 하루씩 진행하며 모자랄 때마다 다시 뽑고 횟수를 센다
// (3) 격자가 아니라 답을 탐색한다 — 구간 lo = 하루 최댓값, hi = 총합       ([3단계] 함정 1
// (4) 이분 탐색 — mid는 lo + (hi - lo) / 2                                 ([3단계] 함정 2
// (5) 인출 횟수가 M 이하면 가능 -> 답으로 기록하고 hi를 낮춰 더 작은 K 탐색 ([3단계] 함정 3, 4
// (6) M을 넘으면 K가 부족한 것 -> lo를 올린다
//
// [트레이스 — 같은 입력에 M = 3 (예제 M = 5는 답이 곧 lo라 탐색이 한 번에 끝난다)]
// money_list = [100,400,300,100,500,101,400], lo = 500(최댓값), hi = 1901(총합)
//   lo=500  hi=1901  mid=1200  cnt=2  <= 3  가능 -> answer=1200, hi=1199
//   lo=500  hi=1199  mid=849   cnt=3  <= 3  가능 -> answer=849,  hi=848
//   lo=500  hi=848   mid=674   cnt=4  >  3  불가 -> lo=675
//   lo=675  hi=848   mid=761   cnt=4  >  3  불가 -> lo=762
//   lo=762  hi=848   mid=805   cnt=3  <= 3  가능 -> answer=805,  hi=804
//   lo=762  hi=804   mid=783   cnt=4  >  3  불가 -> lo=784
//   lo=784  hi=804   mid=794   cnt=4  >  3  불가 -> lo=795
//   lo=795  hi=804   mid=799   cnt=4  >  3  불가 -> lo=800
//   lo=800  hi=804   mid=802   cnt=3  <= 3  가능 -> answer=802,  hi=801
//   lo=800  hi=801   mid=800   cnt=3  <= 3  가능 -> answer=800,  hi=799  -> 종료
// 답 800. cnt가 K에 대해 줄기만 하는(단조) 덕분에 경계가 하나로 정해진다.
//
// [복잡도] 시간 O(N log(총합)) = 100,000 x 30 = 300만, 공간 O(N).
// 실측: N = 100,000 랜덤 입력(M = 300)에서 solution 호출 전체 2.3ms.

#include <iostream>
#include <vector>
#include <numeric>
#include <algorithm>

using namespace std;

vector<int> v;                              // (1)

int countWithdraw(int k)                    // (2)
{
    int cnt = 1;
    int cur = k;

    for (int m : v)
    {
        if (cur < m)
        {
            cnt++;
            cur = k;
        }

        cur -= m;
    }

    return cnt;
}

int solution(vector<int> money_list, int M)
{
    int answer = 0;

    v = money_list;                                     // (1)

    int lo = *max_element(v.begin(), v.end());          // (3)
    int hi = accumulate(v.begin(), v.end(), 0);

    while (lo <= hi)
    {
        int mid = lo + (hi - lo) / 2;                   // (4)

        if (countWithdraw(mid) <= M)                    // (5)
        {
            answer = mid;
            hi = mid - 1;
        }
        else
            lo = mid + 1;                               // (6)
    }

    return answer;
}

// ── 로컬 실행·디버깅용 main (채점기에 제출할 땐 이 블록만 지운다) ──────────
// 함수형 문제라 파일에 진입점이 없다. 그대로 빌드하면 LNK1561(진입점 미정의)이 난다.
int main()
{
    cout << solution({ 100,400,300,100,500,101,400 }, 5) << endl;   // 500
    cout << solution({ 100,400,300,100,500,101,400 }, 3) << endl;   // 800
    cout << solution({ 100,400,300,100,500,101,400 }, 1) << endl;   // 1901
    cout << solution({ 10000 }, 1) << endl;                         // 10000
    cout << solution({ 5,5,5,5 }, 2) << endl;                       // 10
}
