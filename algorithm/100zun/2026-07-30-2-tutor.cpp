// 같은 문제 세 판본: 2026-07-30-2.cpp(내 바텀업) / -2-friend.cpp(지인 코드 분석) / 이 파일(튜터 탑다운)

// ── 튜터 코드 (받은 그대로) ───────────────────────────────────────────
#include <iostream>
#include <algorithm>
#include <queue>
#include <string>
using namespace std;

int dp[1000004];
int n;

int func(int x)
{
    if (x == 1) return 0;

    if (dp[x]) return dp[x];

    int ret = 0;
    ret = func(x - 1) + 1;
    if (x % 3 == 0)
    {
        ret = min(ret, func(x / 3) + 1);
    }
    if (x % 2 == 0)
    {
        ret = min(ret, func(x / 2) + 1);
    }

    return dp[x] = ret;
}

int main()
{
    cin >> n;
    cout << func(n) << "\n";
    return 0;
}
// ─────────────────────────────────────────────────────────────────────

// 읽을 점 1 — INF 없이 시작한다
// 최솟값을 모을 때 보통 큰 값으로 초기화하는데, 여기서는 항상 가능한 연산(1 빼기)의 결과를
// 먼저 넣어 ret 를 채운다.
//     ret = func(x - 1) + 1;
// 이 한 줄이 "유효한 답 하나"를 확보하므로 INF 상수가 필요 없다. 나누기 두 갈래는 조건부라
// 없을 수도 있지만 1 빼기는 언제나 있으니 성립한다.
// 지인 코드가 answer = 0 으로 두어 min(cnt, 0) = 0 에 갇혔던 자리를, 애초에 없애 버린 설계다.

// 읽을 점 2 — dp[x] 가 0이면 "아직 계산 안 함"으로 써도 되는 이유
//     if (dp[x]) return dp[x];
// 이 관용구는 값 0이 정답인 상태가 저장되지 않아야 안전하다.
// 여기서 답이 0인 x 는 x == 1 뿐인데, 그건 위에서 먼저 return 0 으로 빠져나가 dp 에 안 들어간다.
// 그래서 dp[x] == 0 은 곧 미계산이다. (답이 0일 수 있는 문제에서 이 관용구를 그대로 쓰면 틀린다.)

// 읽을 점 3 — 방문 체크가 아니라 값 저장
// 지인 코드의 arr 는 "가 봤는가"만 표시해 나중에 오는 더 짧은 경로를 막았다.
// 이 코드는 dp[x] 에 최소 횟수 자체를 저장하므로, 두 번째로 만난 x 는 계산 없이 확정값을 돌려준다.
// 같은 재귀 골격이라도 무엇을 저장하느냐로 완전탐색과 DP 가 갈린다.

// 읽을 점 4 — 재귀 깊이는 여전히 N
// func(x - 1) 사슬 때문에 최악 깊이가 N = 1,000,000 이다.
// 백준은 C++ 채점 시 스택을 메모리 제한만큼 넉넉히 잡아 주는 편이라 제출은 통과하지만,
// 로컬 기본 스택(1MB급)에서 그냥 돌리면 스택 오버플로가 날 수 있다.
// 바텀업(2026-07-30-2.cpp)은 이 위험 자체가 없다 — 재귀를 안 쓰니 깊이 개념이 없다.

// 세 판본 비교
//   지인 코드   완전탐색 + 방문 체크 → answer 초기값 결함으로 항상 0, arr 범위 밖 접근
//   튜터 코드   탑다운 메모이제이션 → 정답. 깊이 N 의 스택 부담만 남는다
//   내 바텀업   for 반복으로 dp 채우기 → 정답. 깊이 부담 없음, 캐시 접근도 순차적
// 셋 다 점화식은 같다: dp[i] = min(dp[i-1], dp[i/2], dp[i/3]) + 1

// 실측 (MSVC, 로컬 기본 스택)
//   2 -> 1, 10 -> 3, 27 -> 3 : 바텀업 판본과 동일
//   1000000                  : 출력 없이 종료 코드 253 — 스택 오버플로로 죽는다
// 읽을 점 4가 말로 그치지 않고 로컬에서 실제로 재현된다. 백준 채점 환경은 스택을 더 크게
// 잡아 주므로 제출은 통과하지만, 같은 코드를 로컬에서 최대 입력으로 돌리면 이렇게 터진다.
// (로컬에서 확인하려면 링커 옵션으로 스택을 키워야 한다 — MSVC 는 /STACK:268435456)
