// 백준 2217 - 로프 (Silver 4)
// https://www.acmicpc.net/problem/2217

// 문제 설명
// 로프 N개. k개를 병렬로 골라 중량 w를 들면 각 로프에 w/k씩 걸린다.
// 로프를 임의로 골라 들어올릴 수 있는 물체의 최대 중량을 출력.

// 제약 조건
// 1 <= N <= 100,000, 각 로프 최대 중량 <= 10,000 (자연수)

// 예제
// 입력           출력
// 2 / 10 15      20

// 튜터님 테스트 케이스 (전부 통과 확인)
// 3 / 100 2 1              100    최강 1개 단독 (100 > 2*2 > 1*3)
// 1 / 10000                10000
// 5 / 5 10 3 8 15          24     중간이 최적 (8*3)
// 6 / 10 11 12 13 14 15    60     전부 사용이 최적 (10*6)

// 접근
//
// [1단계 — 유형 판별]
// 브루트포스: 로프 부분집합이 2^N개 → N=100,000이면 절대 불가능. 시간복잡도 초과.
// 같은 계산을 여러 번 하나? → 아니오 (겹치는 부분문제 없음) → DP 아님.
// 상태를 배열에 담나? → 담을 상태 자체가 없음 → 그리디. "어떤 선택 기준이 항상 최적인가"를 찾는다.
//
// [2단계 — 핵심 관찰: 병렬의 한계는 최약체]
// k개를 골라 중량 w를 들면 로프 하나가 w/k씩 부담한다.
// 즉 고른 로프 중 "가장 약한 것"이 버티는 게 조건: w/k <= min → w <= min * k.
// 어떤 k개를 고르든 들 수 있는 최대 중량 = (고른 것 중 최솟값) * k.
//
// [3단계 — 그리디 선택 기준: k개를 쓸 거면 가장 튼튼한 k개]
// min * k 에서 k가 같다면 min이 클수록 좋다.
// 고른 k개 중 하나를 그보다 튼튼한 바깥 로프와 바꾸면 min은 절대 작아지지 않는다 (교환 논증).
// → k개 조합을 다 볼 필요 없이, 각 k마다 "상위 k개" 딱 한 가지만 보면 된다. 2^N → N개로 축소.
//
// [4단계 — 구현: 정렬 한 번 + 선형 스캔]
// 내림차순 정렬하면 상위 k개 = 앞에서 k개, 그중 최솟값 = k번째 값.
// 0-index로 i번째까지 쓰면 개수 i+1, 최솟값 v[i] → 최대 중량 v[i] * (i+1).
// i = 0..N-1 을 훑으며 최댓값을 취하면 k=1..N 전부 시도한 것과 같다.
//
// [트레이스 — 5 / 5 10 3 8 15]
// 정렬: 15 10 8 5 3
// i=0: 15*1=15 / i=1: 10*2=20 / i=2: 8*3=24 / i=3: 5*4=20 / i=4: 3*5=15
// 개수가 늘수록 k는 커지지만 min이 작아지는 트레이드오프 → 중간 꼭짓점 24가 답.
//
// [복잡도] 정렬 O(N log N) + 스캔 O(N). 최댓값 10,000*100,000 = 10^9 → int 범위(약 21억) 안.

#include <iostream>
#include <vector>
#include <algorithm>
using namespace std;
#define endl '\n'

int n, ans;
vector<int> v;

int main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    cin >> n;
    for (int i = 0; i < n; i++)
    {
        int c;
        cin >> c;
        v.push_back(c);
    }

    sort(v.rbegin(), v.rend());

    for (int i = 0; i < n; i++)
        ans = max(ans, v[i] * (i + 1));

    cout << ans << endl;
}

// 코드 주석
// int n, ans;                    전역 선언 → 자동 0 초기화. ans는 0에서 시작해 max로만 갱신
// vector<int> v;                 로프 중량 목록. 입력은 main에서 push_back으로 채움
// sort(v.rbegin(), v.rend());    내림차순 정렬. 역방향 반복자(rbegin/rend)를 넘기면 큰 것부터
//                                — 이렇게 하면 "앞에서 i번째까지" = "상위 i+1개"가 됨
// for (int i = 0; i < n; i++)    i = 사용할 로프 개수 후보를 전부 순회 (k = i+1)
// v[i] * (i + 1)                 상위 i+1개 사용 시: 그중 최솟값이 v[i](정렬돼 있어 마지막이 최약)
//                                → 들 수 있는 최대 중량 = 최솟값 * 개수
// ans = max(ans, ...)            k마다 나온 값 중 최댓값이 정답 (k별 최적을 다 비교)
// cout << ans << endl;           endl은 '\n' 매크로 — 출력문 맨 끝에만 사용
