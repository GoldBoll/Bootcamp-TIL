// 방향 자체는 맞다
// 세 연산(3으로 나누기 / 2로 나누기 / 1 빼기)을 모두 시도해 최솟값을 고르는 완전탐색이고,
// arr 로 이미 본 수를 걸러 보려 한 흔적도 있다. 메모이제이션을 향해 가던 중이다.

// 결함 1 — answer 초기값이 0 (치명적, 항상 0 출력)
// answer = 0 으로 시작하는데 바닥에서 answer = min(cnt, answer) 를 한다.
// min(무엇이든, 0) = 0 이므로 answer 는 끝까지 0이다. 어떤 입력이든 0을 출력한다.
// 최솟값을 모으려면 시작값이 "가능한 어떤 답보다도 큰 값"이어야 한다.
//   int answer = 1e9;  (또는 INT_MAX / 큰 상수)
// 최댓값을 모을 때 0에서 시작하는 습관이 그대로 넘어온 자리다.

// 결함 2 — arr 크기가 101인데 n 은 100만까지 (범위 밖 접근)
// arr[n/3], arr[n/2] 는 n 이 303만 넘어가도 배열 밖을 읽는다. 정의되지 않은 동작이라
// 크래시가 날 수도, 조용히 쓰레기 값을 읽어 가지를 잘못 쳐낼 수도 있다.
// 게다가 arr 에는 아무것도 써 넣지 않으므로 전역 배열의 초기값 0이 그대로다.
// 즉 arr[...] == 0 조건은 항상 참이라 걸러 내는 역할을 전혀 하지 못한다.
// 방문 체크를 하려면 (a) 크기를 1,000,001 로 잡고 (b) 방문할 때 값을 써 넣어야 한다.

// 결함 3 — 메모이제이션이 아니라 방문 체크 (같은 수를 다시 계산한다)
// 설령 arr 를 제대로 채워도 "방문 여부"만으로는 최솟값 DP가 성립하지 않는다.
// 먼저 도달한 경로가 더 긴 경로일 수 있는데, 방문했다는 이유로 나중의 짧은 경로를 막아 버린다.
// DP 로 만들려면 방문 여부가 아니라 "그 수를 1로 만드는 최소 횟수"를 저장해야 한다.
//   memo[n] = min(memo[n-1], memo[n/2], memo[n/3]) + 1
// 이러면 같은 수를 두 번째로 만났을 때 계산 없이 확정값을 돌려준다.

// 결함 4 — 재귀 깊이가 곧 N (스택 오버플로)
// repeat(n-1, ...) 갈래는 1씩 내려가는 사슬이라 N = 1,000,000 이면 깊이도 100만이 된다.
// 기본 스택(1MB급)으로는 견디지 못한다. 이 문제에서 탑다운이 위험하고
// 바텀업(for 반복)이 안전한 이유가 여기 있다 — 2026-07-30-2.cpp 의 [3단계] 참고.

// 정리하면
// 결함 1 하나만 고쳐도 "답은 맞지만 시간 초과", 1+2+3 을 고치면 "탑다운 DP",
// 거기에 4까지 피하려면 바텀업으로 뒤집는 순서가 된다.
// 아래는 원본의 구조를 최대한 살려 1~3 을 고친 형태다(깊이 문제는 남아 있어 제출용은 아니다).

#include <iostream>
#include <algorithm>
using namespace std;
#define endl '\n'

const int INF = 1e9;
int n;
int memo[1000004];   // memo[i] = i를 1로 만드는 최소 연산 횟수, 0이면 아직 미계산

int repeat(int cur) {
    if (cur == 1) return 0;
    if (memo[cur]) return memo[cur];              // 방문 여부가 아니라 확정값을 돌려준다

    int best = repeat(cur - 1) + 1;               // 1 빼기 (항상 가능)
    if (cur % 2 == 0) best = min(best, repeat(cur / 2) + 1);
    if (cur % 3 == 0) best = min(best, repeat(cur / 3) + 1);

    return memo[cur] = best;
}

int main() {
    cin >> n;
    cout << repeat(n) << endl;
    return 0;
}

