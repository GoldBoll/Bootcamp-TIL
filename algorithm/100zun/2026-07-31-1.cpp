// 백준 2294 - 동전 2
// https://www.acmicpc.net/problem/2294
// 난이도: solved.ac 기준 Gold V (level 11) — 2026-07-31 조회

// 문제 설명
// n가지 종류의 동전이 있고, 각 동전은 몇 개든 쓸 수 있다.
// 가치의 합이 정확히 k원이 되게 하면서 동전 개수를 최소로 만들고 싶다.
// 그 최소 개수를 출력하고, 어떻게 해도 k원을 만들 수 없으면 -1을 출력한다.

// 제약 조건
// 1 <= n <= 100, 1 <= k <= 10,000
// 동전의 가치 <= 100,000  — k보다 큰 동전이 섞여 들어올 수 있다
// 가치가 같은 동전이 여러 번 주어질 수도 있다
// 시간 1초 / 메모리 128MB

// 예제
// 입력        출력
// 3 15        3        동전 {1, 5, 12}로 15원 -> 5 + 5 + 5 = 3개
// 1
// 5
// 12

// 자체 검증 케이스 (전부 실측 통과)
// 3 15 / 1 5 12        3       예제. 그리디(큰 것부터 12+1+1+1=4)가 지는 반례이기도 하다
// 1 3 / 2              -1      불가능 — 2로는 홀수를 만들 수 없다 (INF 판정 경로)
// 1 5 / 5              1       k와 동전이 같은 경계 — 한 개로 끝
// 1 5 / 100000         -1      k보다 큰 동전 — 안쪽 루프가 한 번도 안 도는지 확인
// 2 6 / 3 3            2       중복 가치 입력 — 두 번 처리해도 답이 안 망가지는지
// 1 10000 / 1          10000   최대 개수 — 답의 상한(= k)을 그대로 찍는 케이스
// 3 10000 / 1 7 13     772     큰 k를 1원이 아닌 동전으로 채우는 경우 (13 × 769 + 1 × 3)

// 스트레스 테스트 (독립 구현 대조로 검증)
// "금액을 정점, 동전을 간선"으로 보는 BFS 완전탐색(0원에서 출발해 k에 처음 닿는 깊이)을
// 따로 구현해 랜덤 소형 입력 20,000개(n = 1..4, 동전 가치 1..12, k = 1..40)와 대조
// -> 20000/20000 일치 (불가능 케이스 -1 포함). 점화식이 문제 규칙을 그대로 옮겼음을 확인했다.

// 접근
//
// [1단계 — 유형 판별]
// 완전탐색: 매 단계 n갈래로 동전을 하나 고르는 트리. 깊이는 최대 k(1원짜리 1만 개)라
// 경우의 수가 n^k 급 — n = 100, k = 10,000에서 완전히 터진다.
// 그리디("큰 동전부터 최대한")는 틀린 기준 — 예제가 그대로 반례다.
//   그리디: 15 = 12 + 1 + 1 + 1 -> 4개 / 정답: 5 + 5 + 5 -> 3개.
//   눈앞에서 가장 큰 12를 집으면 남은 3원을 1원으로만 메워야 해서 손해가 뒤에 몰린다.
// 초과 원인은 "서로 다른 동전 순서가 결국 같은 남은 금액에 도달해 그 아래를 다시 계산"하는 것
// (1 -> 5 와 5 -> 1 이 둘 다 6원에서 만난다) -> 중복 부분문제 -> DP.
//
// [2단계 — DP 설계]
// 상태 dp[j] = j원을 만드는 데 필요한 동전의 최소 개수.
// 마지막에 놓은 동전이 무엇이었는지로 경우를 나눈다 — 그 동전을 coin이라 하면
//   dp[j] = min(dp[j - coin] + 1)   (모든 coin에 대해, j >= coin일 때)
// 바닥은 dp[0] = 0 — 0원은 동전 없이 이미 만들어져 있다.
// 만들 수 없는 금액은 INF로 남겨 두고, 마지막에 dp[k]가 INF면 -1을 출력한다.
// 각 동전을 몇 개든 쓸 수 있으므로(무한 배낭) 안쪽 금액 루프를 **오름차순**으로 돌아
// 같은 동전으로 이미 갱신된 dp[j - coin]을 다시 읽게 둔다 — 이것이 "여러 번 사용"을 뜻한다.
//
// [3단계 — 함정]
// 1) INF를 무엇으로 둘 것인가 — 답이 0이 될 수 있는(dp[0] = 0) 표라 0은 미계산 표시로 못 쓴다.
//    답의 상한이 k = 10,000이므로 10,001을 INF로 두면 값 범위와 절대 겹치지 않는다.
//    0x3f3f3f3f 대신 이 값을 쓰면 dp[j-coin] + 1 이 INF + 1 = 10,002 로 끝나 오버플로 걱정이 없다.
// 2) 동전 가치가 k보다 클 수 있다(최대 100,000 vs k 최대 10,000).
//    `for (int j = coin; j <= k; j++)` 형태면 coin > k일 때 루프가 아예 안 돌아
//    dp 배열 범위 밖을 건드리지 않는다. 별도 if 가드가 필요 없다.
// 3) 가치가 같은 동전이 중복으로 들어와도 무해하다 — 같은 갱신을 한 번 더 할 뿐 min은 그대로다.
// 4) 개수 최소 문제라 동전을 쓰는 순서는 답에 영향이 없다. 그래서 루프 순서(동전 바깥/금액 바깥)
//    어느 쪽도 답이 같다. 다만 "동전 바깥 + 금액 오름차순"이 조합 세기(2293 동전 1)와 같은 골격이라
//    이 형태로 통일해 둔다.
//
// [4단계 — 제한과 자료형]
// 상태 k개 × 동전 n개 = 100 × 10,000 = 10^6 번 갱신. 1초 제한에 한참 여유가 있다.
// 답의 상한은 1원짜리로만 채울 때의 k = 10,000이라 int로 충분하다 — long long을 쓸 이유가 없다.
// 배열은 int × 10,001 = 약 40KB로 128MB 안. 전역에 잡아 0 초기화 흐름을 쓰되,
// 이 문제는 바닥값 0과 미계산을 구분해야 하므로 INF로 명시적으로 덮어쓴다.
//
// [구현 순서]
// (1) 입력 받기 — n(동전 종류 수), k(목표 금액)
// (2) dp 배열을 INF로 채우고 바닥값 dp[0] = 0 설정                  ([2단계] 바닥)
// (3) 바깥 루프: 동전을 하나씩 읽어 그 자리에서 처리 (배열 보관 불필요)
// (4) 안쪽 루프: 금액 오름차순 j = coin..k — 같은 동전 여러 번 허용  ([2단계] 무한 배낭)
//     (coin > k면 루프가 안 돌아 큰 동전이 자동으로 걸러진다)        ([3단계] 함정 2)
// (5) 점화식 적용 dp[j] = min(dp[j], dp[j - coin] + 1)
// (6) dp[k]가 INF면 -1, 아니면 dp[k] 출력                           ([3단계] 함정 1)
//
// [트레이스 — 예제 (n = 3, k = 15, 동전 1 / 5 / 12)]
// 동전 1 처리 후:  dp[j] = j            (1원짜리 j개)
// 동전 5 처리 후:  dp[5]=1 dp[6]=2 dp[7]=3 dp[10]=2 dp[11]=3 dp[12]=4 dp[15]=3
//                  dp[15] = dp[10] + 1 = 3  <- 여기서 이미 정답이 나온다
// 동전 12 처리 후: dp[12] = dp[0] + 1 = 1, dp[13] = 2, dp[14] = 3
//                  dp[15] = min(3, dp[3] + 1 = 4) = 3   <- 12를 쓰면 오히려 손해
// 출력 dp[15] = 3
//
// [복잡도] 시간 O(n × k) = 10^6, 공간 O(k).
// 최대 입력(n = 100, k = 10,000, 동전 대부분이 k 미만이라 안쪽 루프가 거의 다 도는 입력)에서
// DP 루프 구간만 측정해 0.29ms — 1초 제한 대비 세 자릿수 배 여유다.

#include <iostream>
#include <algorithm>
using namespace std;
#define endl '\n'

const int INF = 10001;      // 답의 상한 k = 10,000 보다 크므로 실제 값과 겹치지 않는다

int n, k;
int dp[10001];

int main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    cin >> n >> k;                              // (1)

    fill(dp, dp + k + 1, INF);                  // (2)
    dp[0] = 0;

    for (int i = 0; i < n; i++)                 // (3)
    {
        int coin;
        cin >> coin;

        for (int j = coin; j <= k; j++)         // (4)
            dp[j] = min(dp[j], dp[j - coin] + 1);   // (5)
    }

    if (dp[k] == INF) cout << -1 << endl;       // (6)
    else cout << dp[k] << endl;
}
