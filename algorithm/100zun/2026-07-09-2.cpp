// 백준 1094 - 막대기 (Bronze 2)
// https://www.acmicpc.net/problem/1094

// 문제 설명
// 64cm 막대 하나에서 시작. 합이 X보다 크면 가장 짧은 막대를 절반으로 자르고,
// 절반 하나를 버려도 합이 X 이상이면 버린다. 최종적으로 몇 개의 막대를
// 풀로 붙여 Xcm를 만드는지 출력.

// 제약 조건
// 1 <= X <= 64

// 예제
// 입력   출력
// 23      4
// 32      1
// 64      1
// 48      2

// 접근 — 비트마스킹 (popcount)
// 64 = 2^6에서 절반으로만 자르므로 모든 막대는 2의 거듭제곱(64,32,16,8,4,2,1).
// 시뮬레이션이 하는 일 = X를 2의 거듭제곱의 합으로 분해하는 것 → X의 이진 표현.
//   23 = 10111(2) = 16+4+2+1 → 막대 4개
//   48 = 110000(2) = 32+16   → 막대 2개
// 답 = X에서 켜진 비트 개수. x & 1로 마지막 비트 확인, x >>= 1로 밀며 센다.

#include <iostream>
using namespace std;
#define endl '\n'

int n, cnt;

int main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    cin >> n;
    while (n)
    {
        cnt += n & 1;
        n >>= 1;
    }
    cout << cnt << endl;
}

// 코드 주석
// cnt += n & 1;      마지막 비트가 1이면 그 길이의 막대가 하나 필요
// n >>= 1;           다음 비트로 한 칸 밀기
