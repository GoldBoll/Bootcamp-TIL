// ── 튜터 코드 (받은 그대로, include 만 보충) ──────────────────────────
#include <iostream>
#include <algorithm>
using namespace std;

long long dp[34][34];
int n;

long long func(long long one, long long half)
{
    if (one < 0) return 0;
    if (half < 0) return 0;   // 마이너스로 들어간 놈은 필요없는 경로이다

    // 토큰 줍기
    if (one == 0 && half == 0) return 1;

    // 계산이 됐는지 — 습관으로 붙이는 자리
    long long &ret = dp[one][half];
    if (ret != -1) return dp[one][half];

    ret = 0;

    ret += func(one - 1, half + 1);
    ret += func(one, half - 1);

    return ret;
}

int main()
{
    while (true)
    {
        cin >> n;

        if (n == 0) return 0;

        fill(&dp[0][0], &dp[0][0] + 34 * 34, -1);

        cout << func(n, 0) << endl;
    }
}
// ─────────────────────────────────────────────────────────────────────

// 읽을 점 1 — 왜 여기서는 -1 초기화인가 (1463과 갈리는 지점)
// 같은 튜터의 1463 코드는 `if (dp[x]) return dp[x];` 로 0을 "미계산"으로 썼다.
// 거기서는 답이 0인 상태가 dp 에 저장되지 않기 때문에 그게 안전했다.
// 이 문제는 다르다 — 범위를 벗어난 경로에서 0을 정상적으로 반환하고, 그 0이 표에 들어갈 수 있다.
// 0을 "미계산"으로 쓰면 이미 계산해서 0이 나온 칸을 매번 다시 파고들어 메모가 무력해진다.
// 그래서 답의 값 범위와 겹치지 않는 -1 을 미계산 표시로 쓴다.
// 판단 기준: **0이 정답이 될 수 있는 문제인가**. 그렇다면 -1(혹은 별도 방문 배열)이 필요하다.

// 읽을 점 2 — 참조로 메모 칸을 잡는 관용구
//     long long &ret = dp[one][half];
//     ret = 0;  ret += ...;  return ret;
// 지역 변수에 모았다가 마지막에 대입하는 대신, 표의 칸 자체를 참조로 잡아 바로 누적한다.
// "계산 결과를 저장하는 것을 잊는" 실수가 구조적으로 불가능해진다.

// 읽을 점 3 — 음수 가드로 호출부를 단순하게
//     if (one < 0) return 0;  if (half < 0) return 0;
// 이 두 줄 덕분에 호출부에서 `if (one > 0)` 같은 조건을 달 필요가 없다.
//     ret += func(one - 1, half + 1);
//     ret += func(one, half - 1);
// 조건을 함수 입구 한 곳에 모아 두는 방식이다. 내 바텀업 판본은 반대로 채우는 쪽에
// `if (w > 0)` / `if (h > 0)` 을 달았다 — 어느 쪽이든 되지만, 재귀에서는 입구 가드가 읽기 쉽다.

// 읽을 점 4 — 재귀 깊이가 짧아 탑다운이 안전한 문제
// 한 번 내려갈 때마다 (one + half) 나 half 가 줄어 최대 깊이가 2N = 60 이다.
// 1463(깊이 = N = 100만)과 정반대라, 여기서는 탑다운이 스택 걱정 없이 가장 자연스럽다.
// "탑다운이 위험하다"는 규칙이 아니라 **깊이를 보고 고르는 것**임을 보여 주는 짝 사례다.

// 관찰 — 표를 케이스마다 다시 비운다
//     fill(&dp[0][0], &dp[0][0] + 34*34, -1);
// dp[one][half] 의 값은 입력 n 과 무관하다(그 상태에서 병을 비우는 방법의 수).
// 그래서 케이스마다 지우지 않고 그대로 두면 앞 케이스의 계산을 그대로 재사용할 수 있다.
// 지금도 34x34 = 1156칸 × 최대 1000케이스 = 116만 번 쓰기라 시간 안에 들어오지만,
// 한 번만 채우면 그 비용도 사라진다. (정답에는 영향 없음 — 순수한 낭비)

// 관찰 2 — while (true) 와 입력 종료
// 입력이 0 없이 끝나면 `cin >> n` 이 실패한 뒤에도 루프가 돌아 무한 루프가 된다.
// 문제 입력이 0으로 끝난다고 보장하므로 제출에는 문제없지만,
// `while (cin >> n && n)` 으로 쓰면 스트림이 끝날 때도 안전하게 빠져나온다.

// 두 판본 비교
//   튜터 탑다운   상태를 재귀로 따라가며 필요한 칸만 채운다. 깊이 60이라 안전. -1 초기화 필요
//   내 바텀업     표를 순서대로 전부 채운다. 재귀 없음. 0 초기값 그대로 쓸 수 있고 채우는 순서만 주의
// 점화식은 같다: f(w, h) = f(w-1, h+1) + f(w, h-1), f(0,0) = 1

// 실측 (MSVC, 로컬)
//   예제 6/1/4/2/3/30 -> 132 / 1 / 14 / 2 / 5 / 3814986502092304  (바텀업 판본과 동일)
//   1000케이스(30 반복) -> 정상 종료. 표를 매번 지워도 시간 안에 들어온다
