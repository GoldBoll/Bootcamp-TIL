// 백준 2747 - 피보나치 수 (Bronze 2)
// https://www.acmicpc.net/problem/2747
// 같은 문제 두 방식 분리 보관: 2026-07-30-1.cpp(바텀업 반복) / 2026-07-30-1-td.cpp(탑다운 메모이제이션)

// 문제 설명
// F(0) = 0, F(1) = 1, F(n) = F(n-1) + F(n-2) (n >= 2).
// n이 주어졌을 때 n번째 피보나치 수를 출력한다.

// 제약 조건
// 1 <= n <= 45 (자연수 — n = 0 입력은 없음)
// 시간 1초 / 메모리 128MB

// 예제
// 입력      출력
// 10        55

// 자체 검증 케이스 (전부 통과 확인 — 바텀업 버전과 동일 출력)
// 1         1               최소 입력 (재귀 바닥에서 바로 반환)
// 2         1               첫 재귀 적용 지점 (F(0)+F(1))
// 17        1597            문제 본문에 나열된 값과 대조
// 45        1134903170      최대 입력 — int 상한(2147483647) 아래로 안전, 재귀 깊이 45

// 접근
//
// [1단계 — 유형 판별]
// 브루트포스는 정의 그대로의 재귀 F(n-1) + F(n-2). 호출 수가 F(n)에 비례해
// n = 45면 약 11억 번 → 1초 초과.
// 초과 원인이 "같은 F(n-2)를 여러 갈래에서 다시 계산"하는 중복 부분문제 → DP.
// 탑다운은 이 브루트포스 재귀를 **구조 그대로 두고 메모 한 줄만 얹는** 방식이다.
//
// [2단계 — 메모이제이션]
// dp[n]에 한 번 구한 F(n)을 저장하고, 다음에 같은 n이 들어오면 재귀 없이 즉시 반환.
// 각 n은 딱 한 번만 실제 계산되므로 호출 수가 F(n)에서 O(n)으로 떨어진다.
// 바닥: n <= 1이면 F(n) = n이므로 return n; 한 줄로 F(0)=0, F(1)=1을 동시에 처리.
//
// [3단계 — "dp[n]이 0이면 미계산" 판정이 성립하는 이유]
// 전역 배열 0 초기화를 미계산 표시로 쓰는데, F(0) = 0이라 값 0과 미계산이 충돌할 수 있다.
// 여기서는 n <= 1을 메모에 닿기 **전에** 반환하므로 dp에 실제로 저장되는 값은 n >= 2,
// 즉 F(n) >= 1뿐이다 → 0은 언제나 "아직 계산 안 함"을 뜻해 충돌이 없다.
// (바닥을 dp[0]/dp[1] 대입으로 처리했다면 dp[0] = 0이 미계산과 구분되지 않아
//  +1 인코딩이나 별도 visited 배열이 필요해진다.)
//
// [4단계 — 자료형·재귀 깊이]
// F(45) = 1,134,903,170 < 2^31 - 1 = 2,147,483,647 → int로 들어가지만 여유는 두 배 남짓.
// n을 47 이상으로 늘리는 변형이면 long long 필요.
// 재귀 깊이는 최대 45 — 스택 걱정이 없는 수준. 깊이가 10만 급이면 바텀업이 안전하다.
//
// [트레이스 — 예제]
// fibo(10) → fibo(9) → ... → fibo(1) 반환 1 → 올라오며 dp[2..10] = 1 2 3 5 8 13 21 34 55
// 두 번째 갈래 fibo(8)부터는 dp[8]이 이미 채워져 있어 재귀 없이 반환 → 각 n당 1회 계산
//
// [복잡도] 시간 O(n), 공간 O(n) + 재귀 스택 O(n). n <= 45이라 상한 자체가 무시할 크기.
//
// [바텀업과의 비교]
// 바텀업 — 재귀 스택 없음, n < 2에서 루프를 안 도는 경계만 주의.
// 탑다운 — 브루트포스 재귀 형태를 유지해 점화식이 그대로 읽히고, 실제로 필요한 상태만 계산.
//          대신 스택 깊이와 "0 = 미계산" 충돌을 신경 써야 한다.
// 이 문제는 모든 상태를 다 쓰고 깊이도 얕아 둘이 동등 — 상태가 희소하면 탑다운이 유리하다.

#include <iostream>
using namespace std;
#define endl '\n'

int n;
int dp[46];

int fibo(int here)
{
    if (here <= 1) return here;
    if (dp[here]) return dp[here];

    dp[here] = fibo(here - 1) + fibo(here - 2);
    return dp[here];
}

int main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    cin >> n;

    cout << fibo(n) << endl;
}

// 코드 주석
// int dp[46];                        전역 배열 — 0으로 자동 초기화. 0 = 아직 계산 안 함
// int fibo(int here)                 값을 반환하는 재귀 (전역 ans 없이 반환값 누적 — int dfs() 습관)
// if (here <= 1) return here;        재귀 바닥. F(0) = 0, F(1) = 1이 그대로 here와 같아 한 줄로 처리
//                                    메모를 건드리기 전에 반환하므로 dp에는 F(n) >= 1만 저장된다
// if (dp[here]) return dp[here];     이미 계산된 n이면 재귀를 잘라낸다 — 중복 부분문제 제거의 전부
// dp[here] = fibo(...) + fibo(...);  점화식 그대로. 저장과 반환을 한 곳에서 하므로 저장 누락이 없다
// cout << fibo(n)                    F(45) = 1134903170으로 int 범위 안. n을 47 이상으로 늘리는
//                                    변형이면 long long으로 바꿔야 한다
