// 백준 13305 - 주유소 (Silver 3)
// https://www.acmicpc.net/problem/13305

// 문제 설명
// 일직선 위 도시 N개, 인접 도시 간 도로 N-1개. 1km당 1리터, 기름통 무제한.
// 각 도시 주유소의 리터당 가격이 다를 때, 맨 왼쪽 도시에서 맨 오른쪽 도시까지
// 이동하는 최소 비용을 출력. (출발 시 기름 0 — 첫 도시에서 반드시 주유)

// 제약 조건
// 2 <= N <= 100,000
// 전체 거리 합 <= 1,000,000,000 / 리터당 가격 <= 1,000,000,000 (모두 자연수)

// 예제
// 입력                        출력
// 4 / 2 3 1 / 5 2 4 1         18
// 4 / 3 3 4 / 1 1 1 1         10   (균일 가격)

// 셀프 체크리스트 케이스 (전부 통과 확인)
// 2 / 5 / 3 1                          15      N=2 극단 + 도착지가 최저가여도 무시 (p[n-1] 미사용)
// 4 / 1 1 1 / 9 5 1 1                  15      하락 가격 — 매 도시 mn 갱신
// 4 / 2 3 1 / 1 5 9 9                  6       상승 가격 — 첫 도시에서 전부
// 3 / 10 10 / 5 1 9                    60      틀린 기준 반례 — 첫 도시 몰빵이면 100
// 2 / 1000000000 / 1000000000 1        10^18   오버플로 — long long 필수
// N=10만, 총거리·가격 최대               999990000000000000 (120ms)
//
// 스트레스 테스트 (튜터 케이스 없음 → 독립 구현 대조로 검증)
// dp[도시][기름] 완전탐색 DP를 따로 구현, 랜덤 소형 입력과 대조:
//   로직 20만 케이스 + 실제 실행파일 200케이스 전부 일치 → 그리디 반례 없음 확인

// 접근
//
// [1단계 — 유형 판별]
// 브루트포스: 도시마다 "몇 리터 넣을지" 조합 → 무한대에 가까움. 시간초과.
// 같은 계산 반복 없음 → DP 아님 → 그리디. 기준 하나로 항상 최적이 되는지 찾는다.
//
// [2단계 — 핵심 관찰: 구간별로 생각하면 독립이 된다]
// 총비용 = 각 도로 구간(i번 도시 → i+1번 도시)마다 "그 구간을 달린 기름을 산 가격 × 길이"의 합.
// 구간 i를 달릴 기름은 도시 0..i 중 아무 데서나 미리 사둘 수 있다 (기름통 무제한).
// → 구간 i의 최소 단가 = 지금까지 지나온 도시들의 최저가. 구간마다 독립적으로 최저가를 쓰면 전체 최소.
//
// [3단계 — 그리디 선택 기준: 달리면서 최저가 갱신]
// 왼쪽부터 훑으며 mn = 지금까지 본 최저가를 유지, 구간 비용 = mn * 거리.
// 더 싼 주유소를 만나면 mn 갱신 — 그 뒤 구간부터는 새 최저가로 달린다.
// 교환 논증: 어떤 구간을 최저가보다 비싼 기름으로 달렸다면, 그 리터를 최저가 도시에서
// 미리 사는 것으로 바꿔도 항상 손해가 없다 → 최저가 사용이 최적.
// 1202와 대비: 후보 집합이 "지금까지의 최솟값" 하나로 요약됨 → 힙 불필요, 변수 하나면 충분.
//
// [4단계 — 구현: 정렬조차 없는 O(N) 한 번 훑기]
// 도로 d[0..n-2], 가격 p[0..n-1] 입력. mn = p[0]에서 시작해
// 구간 i마다 mn = min(mn, p[i]) 갱신 후 sum += mn * d[i].
// 마지막 도시 가격 p[n-1]은 절대 쓰이지 않음 (도착지 — 더 갈 구간이 없다).
//
// [트레이스 — 예제 1]
// d = [2,3,1], p = [5,2,4,1]
// 구간0: mn=5, +10 / 구간1: p=2 → mn=2, +6 / 구간2: p=4 무시, mn=2, +2 → 총 18
//
// [복잡도·범위] O(N). 최대 비용 = 총거리 10^9 × 최고가 10^9 = 10^18
// → int(2.1*10^9)는 물론 int 곱셈도 초과. long long(9.2*10^18) 필수, 곱셈 전에 long long이어야 함.

#include <iostream>
#include <vector>
#include <algorithm>
using namespace std;
#define endl '\n'

int n;
long long sum, mn;
vector<long long> d, p;

int main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    cin >> n;
    for (int i = 0; i < n - 1; i++)
    {
        long long c;
        cin >> c;
        d.push_back(c);
    }
    for (int i = 0; i < n; i++)
    {
        long long c;
        cin >> c;
        p.push_back(c);
    }

    mn = p[0];
    for (int i = 0; i < n - 1; i++)
    {
        mn = min(mn, p[i]);
        sum += mn * d[i];
    }

    cout << sum << endl;
}

// 코드 주석
// vector<long long> d, p;        도로 길이 / 리터당 가격. 곱셈(mn * d[i])이 10^18까지 가므로
//                                피연산자 자체를 long long으로 — int끼리 곱하고 담으면 이미 오버플로
// mn = p[0];                     출발 도시에서는 무조건 주유 (기름 0으로 시작)
// mn = min(mn, p[i]);            i번 도시 도착 시점의 "지금까지 최저가" 갱신
// sum += mn * d[i];              구간 i는 최저가 기름으로 달린 것으로 계산 (미리 사둔 셈)
// p[n-1]                         마지막 도시 가격은 사용되지 않음 — 도착지라 더 달릴 구간이 없음
// long long sum;                 전역 0 초기화, 최대 10^18
