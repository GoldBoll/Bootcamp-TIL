// 백준 1463 - 1로 만들기 (Silver 3)
// https://www.acmicpc.net/problem/1463

// 문제 설명
// 정수 X에 세 가지 연산을 쓸 수 있다. X가 3으로 나누어떨어지면 3으로 나누기,
// 2로 나누어떨어지면 2로 나누기, 1 빼기.
// N이 주어졌을 때 1을 만드는 데 필요한 연산 횟수의 최솟값을 출력한다.

// 제약 조건
// 1 <= N <= 1,000,000
// 시간 0.15초 (매우 빡빡 — O(N) 한 번 스캔 이상은 위험) / 메모리 128MB

// 예제
// 입력      출력
// 2         1        2 -> 1
// 10        3        10 -> 9 -> 3 -> 1

// 자체 검증 케이스 (전부 통과 확인)
// 1         0               최소 입력 — 연산 없이 이미 1 (루프 미실행 경계)
// 3         1               3으로 한 번
// 4         2               4 -> 2 -> 1 (2로 두 번)
// 10        3               그리디 반례 — 2로 먼저 나누면 10->5->4->2->1 = 4
// 27        3               3으로 세 번 — 나누기가 계속 먹히는 경우
// 1000000   19              최대 입력 (실측 시간도 함께 확인)
//
// 스트레스 테스트 (독립 구현 대조로 검증)
// BFS 완전탐색(1에서 역방향이 아니라 N에서 정방향 너비 우선)을 따로 구현해
// N = 1..3000 전 구간 답을 대조 → 3000/3000 일치. 점화식 반례 없음 확인.

// 접근
//
// [1단계 — 유형 판별]
// 브루트포스: 매 단계 최대 3갈래 → 트리 크기가 지수. N = 10^6이면 시간초과.
// 그리디("나눌 수 있으면 큰 수로 나눈다")는 틀린 기준 — N = 10에서
//   그리디: 10 -> 5 -> 4 -> 2 -> 1 = 4회 / 정답: 10 -> 9 -> 3 -> 1 = 3회.
//   "1을 빼서 3의 배수로 맞추는" 손해 한 번이 뒤에서 두 번 이득으로 돌아오기 때문에
//   눈앞의 최선이 전체 최선이 아니다 → 그리디 탈락.
// 초과 원인은 서로 다른 경로가 같은 수에 도달해 그 아래를 똑같이 다시 계산하는 것
// (10 -> 9와 10 -> 5 -> 4 -> ... 이 결국 같은 작은 수들을 공유) → 중복 부분문제 → DP.
//
// [2단계 — DP 설계]
// 상태 dp[i] = i를 1로 만드는 최소 연산 횟수. 마지막에 쓴 연산이 무엇이었는지로 경우를 나눈다.
//   1을 뺐다      → dp[i-1] + 1        (항상 가능)
//   2로 나눴다    → dp[i/2] + 1        (i % 2 == 0일 때만)
//   3으로 나눴다  → dp[i/3] + 1        (i % 3 == 0일 때만)
// 이 중 최솟값이 dp[i]. 바닥은 dp[1] = 0 (이미 1이므로 연산 0회).
// 참조하는 첨자가 모두 i보다 작아 i를 오름차순으로 채우면 항상 확정값만 읽는다(바텀업).
//
// [3단계 — 바텀업을 쓰는 이유: 탑다운은 스택이 터진다]
// 같은 점화식을 탑다운 재귀로 써도 논리는 같지만, dp[i-1] 갈래가 1씩 내려가는 사슬이라
// N = 10^6에서 재귀 깊이가 최대 100만이 된다 → 기본 스택(1MB급)으로는 스택 오버플로.
// 2747에서는 깊이 45라 두 방향이 동등했지만, 이 문제는 깊이가 곧 N이라 바텀업이 유일하게 안전하다.
// (2747 비교 메모의 "깊이가 10만 급이면 바텀업" 조건에 정확히 걸리는 사례)
//
// [4단계 — 0.15초 제한과 자료형]
// 상태 10^6개 × 전이 3개 = 300만 연산으로 O(N) 한 번 스캔. 0.15초 안에 충분히 들어온다.
// 대신 이 제한에서는 입출력 가속 3줄이 사실상 필수고, 상태를 재계산하는 구조(탑다운 재귀
// 호출 오버헤드, 매번 min 재탐색)는 여유가 없다.
// 답의 상한은 log2(10^6) 근처(19회)로 int에 한참 못 미치고, 배열은 int × 10^6 = 4MB로 128MB 안.
// dp는 전역에 잡는다 — 지역 배열이면 4MB가 스택에 올라가 그 자체로 터진다.
//
// [트레이스 — 예제 2 (N = 10)]
// dp[1]=0 dp[2]=1 dp[3]=1 dp[4]=2 dp[5]=3 dp[6]=2 dp[7]=3 dp[8]=3 dp[9]=2 dp[10]=3
// dp[10]은 dp[9]+1 = 3 (i-1 갈래)과 dp[5]+1 = 4 (2로 나누기) 중 3 → 그리디가 틀리는 지점
//
// [복잡도] 시간 O(N), 공간 O(N). N = 10^6에서 실측 약 10ms.

#include <iostream>
#include <algorithm>
using namespace std;
#define endl '\n'

int n;
int dp[1000004];

int main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    cin >> n;

    dp[1] = 0;

    for (int i = 2; i <= n; i++)
    {
        dp[i] = dp[i - 1] + 1;

        if (i % 2 == 0)
            dp[i] = min(dp[i], dp[i / 2] + 1);

        if (i % 3 == 0)
            dp[i] = min(dp[i], dp[i / 3] + 1);
    }

    cout << dp[n] << endl;
}

// 코드 주석
// int dp[1000004];               전역 배열 — 4MB. 지역 변수로 잡으면 스택에 4MB가 올라가 터진다.
//                                크기는 제약 10^6 + 여유 (강사 관례 v[1004] 식)
// dp[1] = 0;                     바닥값 — 이미 1이라 연산 0회. 전역 0 초기화와 같은 값이지만
//                                점화식의 시작점임을 코드로 명시
// for (int i = 2; i <= n; i++)   오름차순으로 채워 항상 확정된 작은 값만 읽는다(바텀업).
//                                N = 1이면 루프를 안 돌고 dp[1] = 0이 그대로 출력된다
// dp[i] = dp[i - 1] + 1;         "1 빼기"는 조건 없이 항상 가능 → 최솟값의 기본값으로 먼저 깔아둔다
// if (i % 2 == 0) ... dp[i / 2]  나누기는 나누어떨어질 때만 후보. min으로 더 짧은 경로면 교체
// if (i % 3 == 0) ... dp[i / 3]  2와 3을 각각 독립 후보로 둔다 — 둘 다 가능한 수(6의 배수)에서
//                                한쪽만 보면 최솟값을 놓친다
// min(...)                       <algorithm> 필요. 세 갈래 중 최소가 이 문제의 전부
