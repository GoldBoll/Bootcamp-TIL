// 백준 1931 - 회의실 배정 (Silver 1)
// https://www.acmicpc.net/problem/1931
// (같은 유형 개념 문제: exam1.cpp — 6/17 시험 1번 활동 선택)

// 문제 설명
// 회의실 1개, 회의 N개(시작, 종료). 겹치지 않게 배정할 수 있는 회의의 최대 개수.
// 한 회의가 끝나는 시각에 다음 회의를 바로 시작할 수 있다 (반열린 구간 [s, e)).
// 시작 == 종료인 회의(길이 0)도 존재할 수 있다.

// 제약 조건
// 1 <= N <= 100,000, 0 <= 시각 <= 2^31 - 1 (int 최댓값과 동일 — int로 충분)

// 예제
// 입력 (11개 회의)                                          출력
// (1,4)(3,5)(0,6)(5,7)(3,8)(5,9)(6,10)(8,11)(8,12)(2,13)(12,14)   4

// 튜터님 테스트 케이스 (전부 통과 확인)
// 3 / (2,2)(1,2)(2,3)                    3    동점 함정 — 종료 같으면 시작순 (핵심!)
// 4 / (0,10)(1,2)(2,3)(3,4)              3    긴 회의의 유혹 — 시작순 정렬이 틀리는 이유
// 3 / (3,3)(3,3)(3,3)                    3    길이 0 회의는 같은 시각에 무한정 쌓임
// 5 / (1,3)(2,5)(4,6)(5,8)(7,9)          3    일반 케이스
// 3 / (1,5)(6,10)(11,15)                 3    전혀 안 겹침 — 전부 선택
// 2 / (0,0)(0,0)                         2    last=0 초기값 엣지 — 시각 0 회의도 통과해야 함
// 6 / (1,2)(2,4)(1,4)(4,6)(5,7)(6,8)     4

// 접근
//
// [1단계 — 유형 판별]
// 브루트포스: 회의 부분집합 2^100000 → 시간초과. 가중치 없는 구간 스케줄링은
// "항상 옳은 선택 기준"이 존재 → 그리디 (활동 선택, Activity Selection).
//
// [2단계 — 그리디 기준: 종료가 빠른 회의부터]
// 일찍 끝나는 회의를 고를수록 뒤에 남는 시간이 최대 → 이후 선택지가 가장 넓다.
// 교환 논증: 최적해의 첫 회의를 "가장 일찍 끝나는 회의"로 바꿔도 뒤 회의와 안 겹침 → 손해 없음.
// (시작 시간순은 틀린 기준 — 일찍 시작하는 긴 회의가 방을 독점하는 반례. exam1 서술형 답)
//
// [3단계 — 이 문제의 함정: 종료시간 동점이면 시작시간 오름차순]
// 반례: (2,2)와 (1,2). 종료만으로 정렬해 (2,2)가 먼저 오면
//   (2,2) 선택 → last=2 → (1,2)는 1 < 2 탈락 → 1개. 정답은 (1,2)→(2,2) 2개.
// 길이 0 회의는 같은 종료시각 그룹의 "맨 뒤"가 아니라 제자리(시작순)에 있어야 잡힌다.
// → pair를 {종료, 시작} 순서로 담으면 기본 정렬이 (종료 우선, 동점 시 시작) 을 자동 처리.
//
// [4단계 — 구현: 정렬 + 선형 스캔]
// {end, start}로 정렬 후 한 번 훑으며, 시작 >= last(마지막 선택 회의의 종료)면 선택.
// 반열린 구간이라 == 도 허용(>=). last는 전역 0 초기화 — 시각이 0 이상이라 첫 회의는 항상 통과.
//
// [트레이스 — 예제]
// (종료,시작) 정렬: (4,1)(5,3)(6,0)(7,5)(8,3)(9,5)(10,6)(11,8)(12,8)(13,2)(14,12)
// (4,1)선택 last=4 → (7,5)선택 last=7 → (11,8)선택 last=11 → (14,12)선택 → 4개
//
// [복잡도] 정렬 O(N log N) + 스캔 O(N). 시각 최대 2^31-1 = int 상한이라 int로 안전.

#include <iostream>
#include <vector>
#include <algorithm>
using namespace std;
#define endl '\n'

int n, cnt, last;
vector<pair<int, int>> v;

int main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    cin >> n;
    for (int i = 0; i < n; i++)
    {
        int s, e;
        cin >> s >> e;
        v.push_back({e, s});
    }

    sort(v.begin(), v.end());

    for (auto m : v)
    {
        if (m.second >= last)
        {
            cnt++;
            last = m.first;
        }
    }

    cout << cnt << endl;
}

// 코드 주석
// v.push_back({e, s});           {종료, 시작} 순서로 담기 — pair 기본 정렬(first→second)이
//                                "종료 오름차순 + 동점 시 시작 오름차순"을 그대로 구현 (함정 해결)
// int last;                      마지막으로 선택한 회의의 종료 시각. 전역 0 초기화 → 첫 회의 항상 통과
// for (auto m : v)               범위 기반 for (튜터 스타일 — 인덱스 불필요)
// m.second >= last               m.second = 시작 시각. 반열린 구간이라 종료 == 시작 허용 (>=)
// cnt++; last = m.first;         선택하고 기준 종료 시각 갱신 (m.first = 종료 시각)
