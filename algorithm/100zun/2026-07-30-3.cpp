// 백준 4811 - 알약 (Gold 5)
// https://www.acmicpc.net/problem/4811

// 문제 설명
// 병에 알약 N개가 들어 있다. 매일 병에서 하나를 꺼내는데,
// 한 알(W)이면 반으로 쪼개 반쪽을 먹고 남은 반쪽을 병에 다시 넣고,
// 반쪽(H)이면 그대로 먹는다.
// 2N일이 지나면 W와 H로 이루어진 길이 2N 문자열이 만들어진다.
// 만들 수 있는 서로 다른 문자열의 개수를 구한다.

// 제약 조건
// N <= 30, 테스트 케이스 최대 1000개, 입력 마지막 줄에 0
// 시간 1초 / 메모리 256MB

// 예제
// 입력      출력
// 6         132
// 1         1
// 4         14
// 2         2
// 3         5
// 30        3814986502092304
// 0         (종료)

// 자체 검증 케이스 (전부 통과 확인)
// 1         1                   최소 입력 — 이틀에 WH 하나뿐
// 2         2                   WWHH / WHWH — 첫날은 반드시 W라 W로 시작하는 둘만
// 3         5                   손으로 셀 수 있는 마지막 크기
// 30        3814986502092304    최대 입력 — int 범위를 넘는다는 것을 확인하는 케이스
// 30 30     같은 값 두 번        표를 미리 채워 두므로 반복 질의가 O(1)인지 확인

// 스트레스 테스트 (독립 구현 대조로 검증)
// 문자열을 실제로 전부 만들어 집합에 넣는 완전탐색을 따로 구현해
// N = 1..12 구간에서 DP 값과 대조 -> 12/12 일치 (n=12는 208012).
// 상태 정의와 전이가 문제의 규칙을 정확히 옮겼는지 이 대조로 확인했다.

// 접근
//
// [1단계 — 유형 판별]
// 문자열을 직접 만들어 세면 길이 2N짜리 경우의 수라 N = 30에서 지수로 터진다.
// 그런데 어떤 날의 상황은 "병에 한 알이 w개, 반쪽이 h개" 두 수로 완전히 결정된다.
// 지금까지 무엇을 먹었는지는 앞으로 만들 문자열에 아무 영향이 없다.
// 서로 다른 경로가 같은 (w, h)에 도달하면 그 아래를 똑같이 다시 세게 된다
// -> 중복 부분문제 -> DP.
//
// [2단계 — DP 설계]
// dp[w][h] = 그 상태에서 병을 다 비울 때까지 만들 수 있는 문자열의 개수.
// 그날 꺼낼 수 있는 것은 둘뿐이고, 둘은 문자열의 그 자리 글자가 갈리므로 서로 다른 문자열이다.
//   한 알을 꺼낸다(W) -> 그 알이 사라지고 반쪽이 하나 늘어난다 -> dp[w-1][h+1]
//   반쪽을 꺼낸다(H) -> 반쪽만 하나 줄어든다                  -> dp[w][h-1]
// dp[w][h] = (w > 0 ? dp[w-1][h+1] : 0) + (h > 0 ? dp[w][h-1] : 0)
// 바닥은 dp[0][0] = 1 — 병이 비면 더 쓸 글자가 없는 문자열 하나로 친다.
// 답은 dp[N][0] (한 알 N개, 반쪽 0개에서 시작).
//
// [3단계 — 채우는 순서에 함정이 있다]
// dp[w-1][h+1]은 h가 "더 큰" 칸을 참조한다. h를 바깥 루프로 두고 늘려 가면
// 아직 안 채운 칸을 읽게 된다.
// w를 바깥에 두면 dp[w-1][*]은 앞 줄이라 이미 끝나 있고, dp[w][h-1]은 같은 줄의 왼쪽이라
// h도 늘려 가며 채우면 참조하는 칸이 항상 확정값이다.
//
// [4단계 — 케이스 수와 자료형]
// 케이스가 최대 1000개인데 N은 30 이하라 값이 계속 겹친다. 매번 새로 채우면 같은 계산을
// 1000번 반복하므로, 시작할 때 표를 한 번 채우고 질의는 읽기만 한다.
// 답의 상한은 N = 30일 때 3,814,986,502,092,304 (약 3.8e15)로 int 상한 2.1e9를 크게 넘는다.
// long long(약 9.2e18)이면 충분하다. 표는 31 x 31 x 8바이트 = 8KB로 메모리는 문제되지 않는다.
//
// [트레이스 — 예제 N = 3]
// dp[0][*] = 1        (한 알이 없으면 남은 반쪽을 순서대로 먹는 길 하나뿐)
// dp[1][0] = dp[0][1] = 1
// dp[1][1] = dp[0][2] + dp[1][0] = 1 + 1 = 2
// dp[1][2] = dp[0][3] + dp[1][1] = 1 + 2 = 3
// dp[2][0] = dp[1][1] = 2
// dp[2][1] = dp[1][2] + dp[2][0] = 3 + 2 = 5
// dp[3][0] = dp[2][1] = 5   <- 정답
//
// [복잡도] 표 채우기 O(N^2) = 496칸(w + h <= 30), 질의 O(1). 케이스 수와 무관하다.
// 참고로 이 수열은 카탈란 수다 — W를 여는 괄호, H를 닫는 괄호로 보면
// "닫는 괄호가 앞서지 않는 문자열의 개수"와 같은 구조다.

#include <iostream>
using namespace std;
#define endl '\n'

long long dp[31][31];   // dp[한 알 수][반쪽 수]
int n;

int main() {
    dp[0][0] = 1;
    // w를 바깥에 두어야 dp[w-1][h+1]이 이미 채워져 있다
    for (int w = 0; w <= 30; w++) {
        for (int h = 0; w + h <= 30; h++) {
            if (!w && !h) continue;
            long long sum = 0;
            if (w > 0) sum += dp[w - 1][h + 1];   // 한 알을 꺼내 쪼갠다 (W)
            if (h > 0) sum += dp[w][h - 1];       // 반쪽을 꺼내 먹는다 (H)
            dp[w][h] = sum;
        }
    }

    while (cin >> n && n) {
        cout << dp[n][0] << endl;
    }
    return 0;
}
