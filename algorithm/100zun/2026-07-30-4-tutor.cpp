// 스트레스 테스트 (독립 완전탐색 3종과 대조, 랜덤 3000케이스: n=1..5, k=1..25, 가치 1..12 중복 없음)
//   튜터 순서(동전 바깥·오름차순) == 개수 조합 완전탐색     : 3000/3000
//   금액 바깥으로 뒤집은 판본     == 순열 완전탐색          : 3000/3000
//   안쪽 내림차순 판본            == 부분집합 완전탐색      : 3000/3000
//   튜터 순서와 뒤집은 판본이 다른 값 : 1392건 / 내림차순과 다른 값 : 1724건
//
// 두 코드 출력 대조 (랜덤 120케이스, n=1..20 / k=1..10000 / 가치 1..100000 중복 없음)
//   튜터 == 내 코드 : 120/120 일치, 불일치 0건
//
// 오버플로 실측 (읽을 점 5)
//   동전 2,4,...,200(100종) + k=9999 -> 출력 0 (정답). 중간 칸 dp[9998]의 참값은 5.4210e+68,
//   int로는 1905808116(쓰레기). 2^31을 처음 넘는 칸은 j=244. 답에 닿는 경로가 아니라 전파되지 않음.
