// 자체 검증 케이스 (튜터·내 코드 양쪽 동일 출력)
//   입력                  출력      찌르는 지점
//   1 1 / 1               1         최소 입력. dp[k] += dp[0] 경로 = 바닥값 직접 검증
//   1 10 / 3              0         만들 수 없는 금액. dp[0]=1이 엉뚱한 칸으로 새지 않는지
//   2 10 / 2 4            3         4를 0/1/2개 — 손으로 셀 수 있는 크기의 검산
//   2 3 / 100000 1        1         가치(10만) > k(3). j = temp 시작 조건이 루프를 막아 범위 밖 접근 없음
//   1 10000 / 1           1         k 상한에서 배열 끝 칸(dp[10000]) 접근
//   3 8 / 1 2 5           7         읽을 점 2의 대비 케이스 (내림차순 판본은 1)
//   100 10000 / 901..1000 4426617   최대 입력. 답이 int에 들어가는 구성
//
// 최대 입력 성능 (n=100, k=10000, 벽시계 5회, 제한 0.5초)
//   튜터  8.7 / 7.3 / 7.7 / 20.5 / 6.6 ms
//   내 것 6.4 / 7.3 / 7.3 / 7.1 / 20.1 ms
//   대부분 프로세스 기동 시간이고 DP 루프는 최대 sum(k - c + 1) <= n*k = 100만 회. 두 코드 구별 불가.
