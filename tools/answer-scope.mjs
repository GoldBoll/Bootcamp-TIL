// 색인·발표 대본 등 애초에 개념 문서가 아닌 것
export const NOT_CONCEPT = /^(00_index|CS_추가키워드_복습|발표_|키워드_보강)/;

/** 소주제 답변 보유율 모집단에서 뺄 문서인가 */
// 인용문을 **실제로 대조한다.** 적어만 두면 장식이고, 머리말이 바뀌어도 제외가 그대로 남아
// 그 문서는 영영 안 재진다 — 줄 번호만으로 판정을 기억하다 썩은 것과 같은 실패다.
// 지문이 사라졌으면 문서 성격이 바뀐 것이니 **제외를 거두고 다시 모집단에 넣는다.**
// 공백을 지워 비교한다(줄바꿈·띄어쓰기 편집에 걸리지 않게). 파일을 못 읽으면 제외를 유지한다.
export const outOfAnswerScope = (file, dir = 'raw/cs-notion') => {
  if (NOT_CONCEPT.test(file)) return true;
  const hit = ANSWER_COLLECTION.find(([f]) => f === file);
  if (!hit) return false;
  const frag = hit[1].split('…')[0].replace(/\s+/g, '');
  try {
    const head = readFileSync(join(dir, file), 'utf8').slice(0, 2000).replace(/\s+/g, '');
    return head.includes(frag);
  } catch { return true; }
};
